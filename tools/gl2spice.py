#!/usr/bin/env python3
"""Convert a Yosys gate-level netlist (write_verilog -noattr -noexpr) of sky130_fd_sc_hd cells to a
SPICE .subckt that instantiates the PDK's standard-cell SPICE models.

Usage: gl2spice.py netlist.v top_module out.spice [--ports p1 p2 ...]
- Pin order per cell is read from $PDK_ROOT/sky130A/libs.ref/sky130_fd_sc_hd/spice/sky130_fd_sc_hd.spice.
- Cell power pins: VPWR, VPB -> VDPWR; VGND, VNB -> VGND (added as the first two .subckt ports).
- Bus bits become name_N (e.g. b[3] -> b_3); `assign a = b;` aliases are merged.
- Port order: as in the Verilog module header, buses expanded LSB first, unless --ports is given.
"""
import os, re, sys

PDK = os.environ.get("PDK_ROOT", "/usr/local/share/pdk")
CELLS = os.path.join(PDK, "sky130A/libs.ref/sky130_fd_sc_hd/spice/sky130_fd_sc_hd.spice")
POWER = {"VPWR": "VDPWR", "VPB": "VDPWR", "VGND": "VGND", "VNB": "VGND"}


def cell_pins():
    pins = {}
    for line in open(CELLS):
        if line.lower().startswith(".subckt "):
            f = line.split()
            pins[f[1]] = f[2:]
    return pins


def net(name):
    name = name.strip()
    m = re.fullmatch(r"\\?([A-Za-z_][\w$]*)\s*\[(\d+)\]", name)
    if m:
        return f"{m.group(1)}_{m.group(2)}"
    return name.lstrip("\\")


def main():
    src, top, out = sys.argv[1], sys.argv[2], sys.argv[3]
    user_ports = sys.argv[sys.argv.index("--ports") + 1:] if "--ports" in sys.argv else None
    text = re.sub(r"/\*.*?\*/", "", open(src).read(), flags=re.S)
    mod = re.search(rf"module\s+{top}\s*\((.*?)\);(.*?)endmodule", text, re.S)
    header, body = mod.group(1), mod.group(2)
    widths = {}
    for kind, msb, lsb, names in re.findall(r"\b(input|output|inout)\s*(?:\[(\d+):(\d+)\])?\s*([^;]+);", body):
        for n in names.split(","):
            widths[n.strip()] = (int(msb), int(lsb)) if msb else None
    ports = []
    for p in [x.strip() for x in header.split(",")]:
        w = widths.get(p)
        ports += [f"{p}_{i}" for i in range(min(w), max(w) + 1)] if w else [p]
    if user_ports:
        ports = user_ports
    # aliases from assign statements (union-find)
    parent = {}
    def find(a):
        parent.setdefault(a, a)
        while parent[a] != a:
            parent[a] = parent[parent[a]]; a = parent[a]
        return a
    # widths of every declared net (ports, wires, escaped hierarchical names)
    allw = dict(widths)
    for msb, lsb, names in re.findall(r"\bwire\s*(?:\[(\d+):(\d+)\])?\s*([^;]+);", body):
        for n in names.split(","):
            allw[n.strip()] = (int(msb), int(lsb)) if msb else None
    def bits(expr):
        """Expand a Verilog expression (name, bit, slice, concatenation, constant) to bit nets, MSB first."""
        expr = expr.strip()
        if expr.startswith("{"):
            out = []
            for part in re.findall(r"\\\S+\s|[^,{}\s][^,{}]*", expr[1:-1]):
                out += bits(part)
            return out
        m = re.fullmatch(r"(\d+)'([bh])([0-9a-fA-F_xz]+)", expr)
        if m:
            w = int(m.group(1)); v = int(m.group(3).replace("_", ""), 2 if m.group(2) == "b" else 16)
            return ["VDPWR" if (v >> i) & 1 else "VGND" for i in range(w - 1, -1, -1)]
        m = re.fullmatch(r"(\\?\S+?)\s*\[(\d+):(\d+)\]", expr)
        if m:
            base = m.group(1).lstrip("\\"); hi, lo = int(m.group(2)), int(m.group(3))
            return [f"{base}_{i}" for i in range(hi, lo - 1, -1)]
        m = re.fullmatch(r"(\\?\S+?)\s*\[(\d+)\]", expr)
        if m:
            return [f"{m.group(1).lstrip(chr(92))}_{m.group(2)}"]
        w = allw.get(expr) if expr in allw else allw.get(expr.strip())
        name = expr.lstrip("\\").strip()
        if w:
            return [f"{name}_{i}" for i in range(max(w), min(w) - 1, -1)]
        return [name]
    for lhs, rhs in re.findall(r"assign\s+(.+?)\s*=\s*(.+?)\s*;", body):
        lb, rb_ = bits(lhs), bits(rhs)
        if len(lb) != len(rb_):
            raise SystemExit(f"assign width mismatch: {lhs} = {rhs} ({len(lb)} vs {len(rb_)})")
        for a, b in zip(lb, rb_):
            ra, rb = find(a), find(b)
            if ra == rb:
                continue
            # keep the supply, then a port name, as the representative
            if rb in ("VGND", "VDPWR") or (rb in ports and ra not in ("VGND", "VDPWR")):
                keep, drop = rb, ra
            else:
                keep, drop = ra, rb
            parent[drop] = keep
    pins = cell_pins()
    lines = [f"* {top}: generated by tools/gl2spice.py from {os.path.basename(src)}",
             f".subckt {top} VDPWR VGND " + " ".join(ports)]
    n_inst = 0
    for cell, inst, conns in re.findall(r"(sky130_fd_sc_hd__\w+)\s+(\S+)\s*\((.*?)\);", body, re.S):
        cmap = {p: net(n) for p, n in re.findall(r"\.(\w+)\(([^)]*)\)", conns)}
        order = pins[cell]
        nodes = []
        for p in order:
            if p in POWER:
                nodes.append(POWER[p])
            else:
                nodes.append(find(cmap[p]) if p in cmap and cmap[p] else f"nc_{inst.strip('_')}_{p}")
        lines.append(f"X{inst.strip(chr(92)).strip('_')} " + " ".join(nodes) + f" {cell}")
        n_inst += 1
    # alias ports that were merged away (port driven through an assign): add 0 V sources
    for p in ports:
        r = find(p)
        if r != p:
            lines.append(f"V_alias_{p} {p} {r} 0")
    lines.append(f".ends {top}")
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"{out}: {n_inst} cells, ports: {' '.join(ports)}")


if __name__ == "__main__":
    main()
