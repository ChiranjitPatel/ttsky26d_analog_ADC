#!/usr/bin/env python3
"""Stage 2 report: parse tb_ota / tb_ota_pd results, write results.md and plots/ota.png."""
import os, re
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

H = os.path.dirname(os.path.abspath(__file__))
O = os.path.join(H, "..", "out", "ota")
log = open(os.path.join(O, "tb_ota.log")).read() + open(os.path.join(O, "tb_ota_pd.log")).read()
val = lambda k: float(re.search(rf"^{re.escape(k)}\s*=\s*(\S+)", log, re.M).group(1))
ld = lambda f: np.loadtxt(os.path.join(O, f), skiprows=1)

a0, ugf, pm, iota, offs = val("a0"), val("ugf"), val("pm"), val("iota"), val("offs")
vpeak, vfinal, trise = val("vpeak"), val("vfinal"), val("trise")
ipd = val("ipd_ota")
overshoot = (vpeak - vfinal) / 0.02 * 100

ac = ld("ac.dat"); f, gdb, ph = ac[:, 0], ac[:, 1], ac[:, 2]
rg = ld("range.dat"); vin, err = rg[:, 0], rg[:, 1]
good = np.abs(err) < 1e-3
# longest contiguous region with |error| < 1 mV
best, cur = (0, 0), None
for i, g in enumerate(good):
    if g and cur is None: cur = i
    if (not g or i == len(good) - 1) and cur is not None:
        end = i if g else i - 1
        if end - cur > best[1] - best[0]: best = (cur, end)
        cur = None
cm_lo, cm_hi = vin[best[0]], vin[best[1]]
st = ld("step.dat")

os.makedirs(os.path.join(H, "plots"), exist_ok=True)
fig, ax = plt.subplots(1, 3, figsize=(13, 3.6))
ax[0].semilogx(f, gdb, label="gain [dB]"); ax0b = ax[0].twinx(); ax0b.semilogx(f, ph, "C1", label="phase [deg]")
ax[0].axhline(0, color="k", lw=0.5); ax[0].set(xlabel="f [Hz]", ylabel="gain [dB]", title=f"Open loop: {a0:.1f} dB, UGF {ugf/1e6:.2f} MHz, PM {pm:.0f}°")
ax0b.set_ylabel("phase [deg]")
ax[1].plot(vin, err * 1e3); ax[1].axvspan(0.55, 0.80, alpha=0.1, label="needed (Vbe range)")
ax[1].set(xlabel="Vin [V]", ylabel="out − in [mV]", title="Follower error (input range)", ylim=(-10, 10)); ax[1].legend(fontsize=7)
ax[2].plot(st[:, 0] * 1e6, st[:, 1] * 1e3, label="out"); ax[2].plot(st[:, 0] * 1e6, st[:, 2] * 1e3, "--", label="in")
ax[2].set(xlabel="t [us]", ylabel="mV", title="Follower 20 mV step", xlim=(4.9, 5.6)); ax[2].legend(fontsize=7)
for a in ax: a.grid(alpha=0.3)
fig.tight_layout(); fig.savefig(os.path.join(H, "plots", "ota.png"), dpi=90)

ok = lambda c: "✅" if c else "❌"
rows = [
    ("DC open-loop gain", f"{a0:.1f} dB", "≥ 50 dB", ok(a0 >= 50)),
    ("Unity-gain frequency (CL = 0.5 pF)", f"{ugf/1e6:.2f} MHz", "—", ""),
    ("Phase margin (CL = 0.5 pF)", f"{pm:.1f}°", "≥ 60°", ok(pm >= 60)),
    ("Follower step overshoot (20 mV)", f"{overshoot:.1f} %", "—", ""),
    ("Follower 10–90 % rise time", f"{trise*1e9:.0f} ns", "—", ""),
    ("Systematic offset (follower at 0.68 V)", f"{offs*1e6:.0f} µV", "—", ""),
    ("Input range, follower error < 1 mV", f"{'≤ ' if best[0] == 0 else ''}{cm_lo:.2f} … {cm_hi:.2f} V", "covers 0.55 … 0.80 V", ok(cm_lo <= 0.55 and cm_hi >= 0.80)),
    ("Supply current (OTA only)", f"{iota*1e6:.2f} µA", "—", ""),
    ("Power-down current (OTA only)", f"{ipd*1e9:.2f} nA", "—", ""),
    ("Input offset σ (Monte Carlo)", "Phase 2", "≤ 2 mV", ""),
]
md = ["# Stage 2 — ota results", "", "Phase 1: tt, 27 °C, VDPWR 1.80 V, biased from `bias_gen`.",
      "Generated by `report.py` from `tb_ota.spice` and `tb_ota_pd.spice`.", "",
      "| Quantity | Result | Target | |", "|---|---|---|---|"]
md += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in rows]
md += ["", "![ota](plots/ota.png)", ""]
open(os.path.join(H, "results.md"), "w").write("\n".join(md))
print("\n".join(md))
