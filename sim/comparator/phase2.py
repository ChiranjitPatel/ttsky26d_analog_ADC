#!/usr/bin/env python3
"""Comparator Phase 2 report from tb_cmp_mc.spice runs (tools/run_corners.py):
  ../out/corners/cmp_mc.csv       --mc 100 --mc-corner tt_mm   (mismatch, tt, 27 C, 1.8 V)
  ../out/corners/cmp_corners.csv  --temps=-40,27,125 --vdd=1.62,1.8,1.98 (5 corners, no mismatch)
vos = toggle point - inn (from vtog, which every run prints); tdec = decision time at +1 mV, valid only where the
offset is below 1 mV (otherwise +1 mV is not an overdrive and the measurement has no event). Writes phase2.md."""
import csv, os
import numpy as np
H = os.path.dirname(os.path.abspath(__file__))
C = os.path.join(H, "..", "out", "corners")
out = ["# Comparator Phase 2 (M2 sizing: xp/xn load caps 4/1.5, preamp load 0.5/8)\n",
       "Generated by `phase2.py` from `tb_cmp_mc.spice` (toggle point on a 0.5 mV/cycle ramp at 10 MHz; decision "
       "time at +1 mV).\n"]
f = os.path.join(C, "cmp_mc.csv")
if os.path.exists(f):
    r = list(csv.DictReader(open(f)))
    v = np.array([float(x["vtog"]) - 0.716 for x in r if x.get("vtog")]) * 1e3
    t = np.array([float(x["tdec"]) for x in r if x.get("tdec")]) * 1e9
    out += ["## Monte Carlo (mismatch, `tt_mm`, 27 °C, 1.8 V)\n", "| Quantity | Result | Target |", "|---|---|---|",
            f"| Offset σ ({len(v)} seeds) | **{v.std(ddof=1):.1f} mV** (mean {v.mean():+.1f} mV) | A7: ≤ 10 mV ❌ |",
            f"| \\|offset\\|: median / 95th pct / worst | {np.median(abs(v)):.1f} / {np.percentile(abs(v), 95):.1f} / "
            f"{abs(v).max():.1f} mV | |",
            f"| Offset in LSB (4.72 mV) | σ {v.std(ddof=1) / 4.72:.1f} LSB, 95th pct {np.percentile(abs(v), 95) / 4.72:.1f} LSB | |",
            f"| Decision time at 1 mV overdrive ({len(t)} seeds with offset < 1 mV) | max {t.max():.2f} ns | A10: ≤ 50 ns |", ""]
f = os.path.join(C, "cmp_corners.csv")
if os.path.exists(f):
    r = list(csv.DictReader(open(f)))
    rows = [(x["corner"], x["temp"], x["vdd"], (float(x["vtog"]) - 0.716) * 1e3 if x.get("vtog") else None,
             float(x["tdec"]) * 1e9 if x.get("tdec") else None) for x in r]
    v = [x[3] for x in rows if x[3] is not None]; t = [x[4] for x in rows if x[4] is not None]
    worst = max(rows, key=lambda x: x[4] or 1e9)
    out += [f"## Corners ({len(rows)} runs: tt/ff/ss/fs/sf × −40/27/125 °C × 1.62/1.8/1.98 V, no mismatch)\n",
            "| Quantity | Result | Target |", "|---|---|---|",
            f"| Systematic offset | {min(v):+.1f} … {max(v):+.1f} mV ({len(v)}/{len(rows)} runs) | |",
            f"| Decision time at 1 mV | {min(t):.2f} … {max(t):.2f} ns ({len(t)}/{len(rows)} runs; slowest "
            f"{worst[0]} {worst[1]} °C {worst[2]} V) | A10: ≤ 50 ns {'✅' if t and max(t) <= 50 and len(t) == len(rows) else '❌'} |",
            "", "| corner | T (°C) | VDD (V) | offset (mV) | t_dec (ns) |", "|---|---|---|---|---|"]
    out += [f"| {a} | {b} | {c} | {'—' if d is None else f'{d:+.2f}'} | {'—' if e is None else f'{e:.2f}'} |"
            for a, b, c, d, e in rows]
txt = "\n".join(out)
print(txt)
open(os.path.join(H, "phase2.md"), "w").write(txt + "\n")
