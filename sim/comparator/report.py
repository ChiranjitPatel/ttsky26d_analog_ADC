#!/usr/bin/env python3
"""Stage 6 report: comparator decisions, decision time, common-mode range, kickback, toggle point."""
import os, re
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

H = os.path.dirname(os.path.abspath(__file__))
O = os.path.join(H, "..", "out", "comparator")
log = open(os.path.join(O, "tb_cmp.log")).read()
ia = abs(float(re.search(r"^ia_avg\s*=\s*(\S+)", log, re.M).group(1)))
d = np.loadtxt(os.path.join(O, "dec.dat"), skiprows=1)
t, ck, aop, aon, bop, bon = d[:, 0], d[:, 1], d[:, 2], d[:, 3], d[:, 4], d[:, 5]
qs = {k: d[:, 6 + i] for i, k in enumerate("abcdef")}

ra, rb, times = [], [], []
cycles = range(0, 11)
for c in cycles:
    t0 = 0.5e-6 + c * 1e-6; m = (t >= t0) & (t < t0 + 0.45e-6)
    kc = np.argmax(m & (ck > 0.9))
    ka = np.argmax(m & (abs(aop - aon) > 0.9)); kb = np.argmax(m & (abs(bop - bon) > 0.9))
    ra.append(aop[ka] > aon[ka]); rb.append(bon[kb] > bop[kb]); times.append(t[ka] - t[kc])
# q at the end of each evaluation window
qend = {k: [v[np.argmin(abs(t - (0.95e-6 + c * 1e-6)))] > 0.9 for c in cycles] for k, v in qs.items()}
expect = {"a": True, "b": False, "c": True, "d": False, "e": True, "f": False}
q_ok = {k: all(x == expect[k] for x in v) for k, v in qend.items()}

k = np.loadtxt(os.path.join(O, "kick.dat"), skiprows=1)
tk, ckk, kin, qsr, rp = k[:, 0], k[:, 1], k[:, 2], k[:, 3], k[:, 4]
pre = [kin[np.argmin(abs(tk - (0.45e-6 + c * 1e-6)))] for c in range(0, 7)]
drift = pre[-1] - pre[1]
peak = max(abs(kin[(tk > 0.5e-6 + c * 1e-6) & (tk < 1.0e-6 + c * 1e-6)] - pre[c]).max() for c in range(0, 6))
states = [qsr[np.argmin(abs(tk - (0.95e-6 + c * 1e-6)))] > 0.9 for c in range(0, 6)]
vin_at = [rp[np.argmin(abs(tk - (0.5e-6 + c * 1e-6)))] for c in range(0, 6)]
toggle = None
for c in range(1, 6):
    if states[c] != states[c - 1]:
        toggle = (vin_at[c - 1], vin_at[c])

os.makedirs(os.path.join(H, "plots"), exist_ok=True)
fig, ax = plt.subplots(1, 3, figsize=(14, 3.6))
m = (t > 2.4999e-6) & (t < 2.5025e-6)
ax[0].plot((t[m] - 2.5e-6) * 1e9, aop[m], label="op (inp = vcm+1 mV)"); ax[0].plot((t[m] - 2.5e-6) * 1e9, aon[m], label="on")
ax[0].plot((t[m] - 2.5e-6) * 1e9, ck[m], "k:", label="clk")
ax[0].set(xlabel="t − 2.5 µs [ns]", ylabel="V", title=f"Decision at 1 mV: {np.mean(times)*1e9:.2f} ns"); ax[0].legend(fontsize=7)
ax[1].plot(tk * 1e6, (kin - 0.6) * 1e3); ax[1].set(xlabel="t [µs]", ylabel="v(inp) − 0.6 V [mV]", title="Kickback on a floating 2.4 pF input")
ax[2].plot(tk * 1e6, qsr, label="q"); ax2 = ax[2].twinx(); ax2.plot(tk * 1e6, (rp - 0.6) * 1e3, "C1", label="inp − inn [mV]")
ax[2].set(xlabel="t [µs]", ylabel="q [V]", title="Slow ramp across inn"); ax2.set_ylabel("inp − inn [mV]")
for a in ax: a.grid(alpha=0.3)
fig.tight_layout(); fig.savefig(os.path.join(H, "plots", "comparator.png"), dpi=90)

ok = lambda c: "✅" if c else "❌"
rows = [
    ("A10", "Decision time at 1 mV overdrive (clk 50 % → |op−on| > 0.9 V)", f"{np.mean(times)*1e9:.2f} ns", "≤ 50 ns", ok(max(times) <= 50e-9), "1"),
    ("—", "Correct decisions, +1 mV / −1 mV at vcm = 0.6 V", f"{sum(ra)}/{len(ra)}, {sum(rb)}/{len(rb)}", "all", ok(all(ra) and all(rb)), "1"),
    ("—", "Correct decisions ±1 mV at CM 0.2 V and 1.0 V", f"{'ok' if all(q_ok[x] for x in 'cdef') else 'FAIL'}", "all", ok(all(q_ok[x] for x in 'cdef')), "1"),
    ("—", "Kickback: drift of a floating 2.4 pF input over 5 cycles", f"{drift*1e6:+.1f} µV", "≤ 0.25 LSB = 1.2 mV", ok(abs(drift) <= 1.2e-3), "1"),
    ("—", "Kickback: peak excursion during evaluation (returns at reset)", f"{peak*1e3:.2f} mV", "—", "", "1"),
    ("—", "Toggle point (slow ramp, inn = 0.6 V)", f"between {toggle[0]*1e3-600:+.2f} and {toggle[1]*1e3-600:+.2f} mV" if toggle else "no toggle", "≈ 0 (offset at tt)", ok(toggle is not None), "1"),
    ("—", "Average supply current at 1 MHz clock", f"{ia*1e9:.0f} nA", "—", "", "1"),
    ("A7", "Offset σ (Monte Carlo)", "Phase 2", "≤ 10 mV", "", "2"),
    ("A8", "Input-referred noise", "Phase 2", "≤ 1.19 mV rms", "", "2"),
]
md = ["# Stage 6 — comparator results", "",
      "tt, 27 °C, VDPWR 1.80 V, clk 1 MHz. reltol 1e-5 (see README). Generated by `report.py` (`./run.sh`).", "",
      "| Spec | Quantity | Result | Target | | Phase |", "|---|---|---|---|---|---|"]
md += [f"| {a} | {b} | {c} | {d_} | {e} | {f} |" for a, b, c, d_, e, f in rows]
md += ["", "![comparator](plots/comparator.png)", ""]
open(os.path.join(H, "results.md"), "w").write("\n".join(md))
print("\n".join(md))
