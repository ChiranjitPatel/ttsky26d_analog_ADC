#!/usr/bin/env python3
"""Stage 3 report: parse tb_bandgap / tb_bandgap_loop / tb_bandgap_pd, write results.md and plots/bandgap.png."""
import os, re
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

H = os.path.dirname(os.path.abspath(__file__))
O = os.path.join(H, "..", "out", "bandgap")
log = "".join(open(os.path.join(O, f)).read() for f in ("tb_bandgap.log", "tb_bandgap_loop.log", "tb_bandgap_pd.log"))
val = lambda k: float(re.search(rf"^{re.escape(k)}\s*=\s*(\S+)", log, re.M).group(1))
ld = lambda f: np.loadtxt(os.path.join(O, f), skiprows=1)

vbg, itot, ibg, dvin, su = val("v(vbg)"), val("itot"), val("ibg"), val("dv_in"), val("v(xbg.su)")
t0, fu, phu = val("t0"), val("fu"), val("phu"); pm = 180 + phu
psrr_dc, psrr_1m = val("psrr_dc"), val("psrr_1m")
v162, v198 = val("vbg162"), val("vbg198"); line = (v198 - v162) / 0.36 * 1e3
ipd = val("ipd")
tt = ld("temp.dat"); T, vT = tt[:, 0], tt[:, 1]
v27 = vT[np.argmin(abs(T - 27))]; tc = (vT.max() - vT.min()) / v27 / (T[-1] - T[0]) * 1e6

def settle(f, ramp_end):
    d = ld(f); t, v = d[:, 0], d[:, 1]
    bad = np.where(abs(v - v[-1]) > 0.01 * v[-1])[0]
    return d, max(t[bad[-1] + 1] - ramp_end, 0.0)
st_f, ts_f = settle("startup.dat", 1e-6)
st_s, ts_s = settle("startup_slow.dat", 100e-6)
lp = ld("loop.dat"); ln = ld("line.dat")

os.makedirs(os.path.join(H, "plots"), exist_ok=True)
fig, ax = plt.subplots(2, 3, figsize=(14, 7))
ax[0, 0].plot(T, vT * 1e3); ax[0, 0].set(xlabel="T [°C]", ylabel="VBG [mV]", title=f"VBG vs T (tt): {tc:.0f} ppm/°C box")
ax[0, 1].plot(ln[:, 0], ln[:, 1] * 1e3); ax[0, 1].axvspan(1.62, 1.98, alpha=0.1)
ax[0, 1].set(xlabel="VDPWR [V]", ylabel="VBG [mV]", title=f"Line: {line:.1f} mV/V (1.62–1.98 V)", ylim=(vbg * 1e3 - 60, vbg * 1e3 + 20))
ax[0, 2].semilogx(lp[:, 0], lp[:, 3]); ax[0, 2].set(xlabel="f [Hz]", ylabel="PSRR [dB]", title="PSRR (VDPWR → VBG)")
a = ax[1, 0]; a.semilogx(lp[:, 0], lp[:, 1], label="|T| [dB]"); a.axhline(0, color="k", lw=0.5)
b = a.twinx(); b.semilogx(lp[:, 0], lp[:, 2], "C1", label="phase [deg]"); b.set_ylabel("phase [deg]")
a.set(xlabel="f [Hz]", ylabel="|T| [dB]", title=f"Loop gain: {t0:.0f} dB, fu {fu/1e6:.2f} MHz, PM {pm:.0f}°")
for axx, d, ttl in ((ax[1, 1], st_f, "Startup, 1 µs ramp"), (ax[1, 2], st_s, "Startup, 100 µs ramp")):
    axx.plot(d[:, 0] * 1e6, d[:, 1], label="vbg"); axx.plot(d[:, 0] * 1e6, d[:, 2], label="vgp"); axx.plot(d[:, 0] * 1e6, d[:, 3], label="su")
    axx.set(xlabel="t [µs]", ylabel="V", title=ttl); axx.legend(fontsize=7)
ax[1, 1].set_xlim(0, 10)
for a in ax.flat: a.grid(alpha=0.3)
fig.tight_layout(); fig.savefig(os.path.join(H, "plots", "bandgap.png"), dpi=85)

ok = lambda c: "✅" if c else "❌"
rows = [
    ("B1", "VBG", f"{vbg:.4f} V", "1.21 … 1.29 V (typ 1.25)", ok(1.21 <= vbg <= 1.29), 1),
    ("B2", "Supply current, bandgap_core + bias_gen", f"{itot*1e6:.1f} µA (core {ibg*1e6:.1f})", "≤ 50 µA", ok(itot <= 50e-6), 1),
    ("B3", "Startup to 1 % after a 1 µs ramp", f"{ts_f*1e6:.2f} µs after ramp end", "≤ 20 µs", ok(ts_f <= 20e-6), 1),
    ("—", "Startup, 100 µs ramp (rule 7)", f"settled {ts_s*1e6:.1f} µs after ramp end", "starts from 0 V", ok(ts_s <= 20e-6), 1),
    ("—", "Loop gain at DC / crossover", f"{t0:.1f} dB / {fu/1e6:.2f} MHz", "—", "", 1),
    ("—", "Loop phase margin (Middlebrook)", f"{pm:.1f}°", "≥ 60° (stage target)", ok(pm >= 60), 1),
    ("—", "OTA input difference vb − va", f"{dvin*1e6:.0f} µV", "—", "", 1),
    ("—", "Startup node su when running", f"{su*1e3:.1f} mV", "MSU1 off", ok(su < 0.1), 1),
    ("B4", "Line regulation 1.62–1.98 V", f"{line:.1f} mV/V", "≤ 10 mV/V", ok(line <= 10), 2),
    ("B5", "Temperature coefficient, −40…125 °C (tt only)", f"{tc:.1f} ppm/°C", "≤ 50 ppm/°C", ok(tc <= 50), 2),
    ("B7", "PSRR at DC / 1 MHz", f"{psrr_dc:.1f} / {psrr_1m:.1f} dB", "≥ 40 / ≥ 20 dB", ok(psrr_dc >= 40 and psrr_1m >= 20), 2),
    ("B8", "Power-down current (bandgap_core + bias_gen)", f"{ipd*1e9:.2f} nA", "≤ 1 µA", ok(ipd <= 1e-6), 2),
]
md = ["# Stage 3 — bandgap_core results", "",
      "tt, 27 °C, VDPWR 1.80 V unless noted; biased from `bias_gen`. Generated by `report.py` (`./run.sh`).",
      "Phase-2 rows are early checks at tt only; corners, temperature and supply sweeps across corners follow in Phase 2.", "",
      "| Spec | Quantity | Result | Target | | Phase |", "|---|---|---|---|---|---|"]
md += [f"| {a} | {b} | {c} | {d} | {e} | {f} |" for a, b, c, d, e, f in rows]
md += ["", "![bandgap](plots/bandgap.png)", ""]
open(os.path.join(H, "results.md"), "w").write("\n".join(md))
print("\n".join(md))
