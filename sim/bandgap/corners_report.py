#!/usr/bin/env python3
"""Phase 2 summary for bandgap_core: reads ../out/corners/tb_bandgap/ (tools/run_corners.py) and writes
corners.md + plots/corners.png. Run from sim/bandgap after:
    ../../tools/run_corners.py tb_bandgap.spice --corners tt,ff,ss,fs,sf,ll,hh --temps=-40,27,125 --vdd 1.62,1.8,1.98
Each run also contains a -40...125 C sweep (temp.dat) at its supply; the TC uses the box method.
Monte Carlo (mismatch) is separate: tb_bandgap_mc.spice + mc_stats.py.
"""
import csv, os
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

base = "../out/corners/tb_bandgap"
rows = list(csv.DictReader(open(f"{base}/results.csv")))
f = lambda r, k: float(r[k]) if r.get(k) not in (None, "") else float("nan")
CORNERS = ["tt", "ff", "ss", "fs", "sf", "ll", "hh"]
for r in rows:
    r["T"], r["V"] = int(r["temp"]), float(r["vdd"])
    r["vbg"] = f(r, "vbg_op")
    r["line"] = (f(r, "vbg198") - f(r, "vbg162")) / 0.36 * 1e3          # mV/V
    # startup: both ramps end at the operating point, and no sustained oscillation after the fast ramp
    r["start_ok"] = (abs(f(r, "vbg_fast") / r["vbg"] - 1) < 0.01 and abs(f(r, "vbg_slow") / r["vbg"] - 1) < 0.01
                     and f(r, "vbg_fmax") - f(r, "vbg_fmin") < 0.01 * r["vbg"])
    td = os.path.join(base, r["tag"], "temp.dat")
    if os.path.exists(td):
        d = np.loadtxt(td, skiprows=1)
        r["tc"] = (d[:, 1].max() - d[:, 1].min()) / d[:, 1].mean() / 165 * 1e6     # ppm/C, box method
        r["curve"] = (d[:, 0], d[:, 1])
    else:
        r["tc"] = float("nan")
nom = next(r for r in rows if r["corner"] == "tt" and r["T"] == 27 and r["V"] == 1.8)["vbg"]
at27 = [r for r in rows if r["T"] == 27 and r["V"] == 1.8]
allv = [r["vbg"] for r in rows]
bad = [r["tag"] for r in rows if r["rc"] != "0" or not (0.5 < r["vbg"] < 2)]
st_bad = [r["tag"] for r in rows if not r["start_ok"]]
tcr = [r for r in rows if r["V"] == 1.8 and r["T"] == 27]
L = ["# bandgap_core — Phase 2 corners (generated by corners_report.py)", "",
     f"{len(rows)} runs: corners {'/'.join(CORNERS)} (ll/hh = low/high resistor corner) × −40/27/125 °C × "
     f"VDPWR 1.62/1.80/1.98 V. Failed runs: {len(bad)}" + (f" ({', '.join(bad)})" if bad else "") + ".", "",
     "## VBG at 27 °C, 1.80 V", "", "| corner | VBG (V) | vs tt | TC −40…125 °C (ppm/°C) | line (mV/V) |", "|---|---|---|---|---|"]
for c in CORNERS:
    r = next(x for x in tcr if x["corner"] == c)
    L.append(f"| {c} | {r['vbg']:.4f} | {(r['vbg']/nom-1)*100:+.2f} % | {r['tc']:.1f} | {r['line']:.2f} |")
L += ["", "## Summary over all runs", "", "| Spec | Quantity | Result | Target | |", "|---|---|---|---|---|",
      f"| B6 | VBG spread, all corners at 27 °C / 1.8 V | {min(r['vbg'] for r in at27):.4f} … {max(r['vbg'] for r in at27):.4f} V "
      f"({(min(r['vbg'] for r in at27)/nom-1)*100:+.1f} / {(max(r['vbg'] for r in at27)/nom-1)*100:+.1f} %) | ±3 % (untrimmed) | "
      f"{'✅' if max(abs(r['vbg']/nom-1) for r in at27) <= 0.03 else '❌'} |",
      f"| — | VBG, every corner × T × VDD | {min(allv):.4f} … {max(allv):.4f} V | — | |",
      f"| B5 | TC, worst corner (1.8 V) | {max(r['tc'] for r in tcr):.1f} ppm/°C | ≤ 50 ppm/°C | {'✅' if max(r['tc'] for r in tcr) <= 50 else '❌'} |",
      f"| B4 | Line regulation, worst run | {max(abs(r['line']) for r in rows):.2f} mV/V | ≤ 10 mV/V | {'✅' if max(abs(r['line']) for r in rows) <= 10 else '❌'} |",
      f"| B3 | Startup (1 µs and 100 µs ramps, settles, no oscillation) | {len(rows)-len(st_bad)}/{len(rows)} runs | all | {'✅' if not st_bad else '❌'} |"]
if st_bad:
    L += ["", "Startup problems: " + ", ".join(st_bad)]
L += ["", "Mismatch (Monte Carlo, `tb_bandgap_mc.spice`, 100 seeds, tt): see `README.md`."]
open("corners.md", "w").write("\n".join(L) + "\n")

fig, ax = plt.subplots(1, 2, figsize=(11, 4)); fig.patch.set_facecolor("white")
for c, col in zip(CORNERS, ["k", "C3", "C0", "C2", "C1", "C4", "C5"]):
    r = next(x for x in tcr if x["corner"] == c)
    if "curve" in r:
        ax[0].plot(r["curve"][0], r["curve"][1], color=col, label=c)
    ax[1].plot([1.62, 1.8, 1.98], [next(x for x in rows if x["corner"] == c and x["T"] == 27 and x["V"] == v)["vbg"] for v in (1.62, 1.8, 1.98)], "o-", color=col, label=c)
ax[0].set(xlabel="temperature [°C]", ylabel="VBG [V]", title="VBG vs temperature (1.8 V)"); ax[0].grid(alpha=0.3); ax[0].legend(fontsize=7)
ax[1].set(xlabel="VDPWR [V]", ylabel="VBG [V]", title="VBG vs supply (27 °C)"); ax[1].grid(alpha=0.3); ax[1].legend(fontsize=7)
fig.tight_layout(); os.makedirs("plots", exist_ok=True); fig.savefig("plots/corners.png", dpi=110, facecolor="white")
print("\n".join(L))
