#!/usr/bin/env python3
"""Stage 4 report: VPTAT level, slope, linearity, temperature-sensor resolution; loop margin with the branch."""
import os, re
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

H = os.path.dirname(os.path.abspath(__file__))
O = os.path.join(H, "..", "out", "ptat")
log = open(os.path.join(O, "tb_ptat.log")).read() + open(os.path.join(O, "tb_ptat_loop.log")).read()
val = lambda k: float(re.search(rf"^{re.escape(k)}\s*=\s*(\S+)", log, re.M).group(1))
vptat, dvb_branch, dvb_load = val("v(vptat1)"), val("dvbg_branch"), val("dvbg_load")
t0, fu, pm = val("t0"), val("fu"), 180 + val("phu")
d = np.loadtxt(os.path.join(O, "temp.dat"), skiprows=1); T, vp = d[:, 0], d[:, 1]
slope, icpt = np.polyfit(T, vp, 1)
nonlin = vp - (slope * T + icpt)
TK = T + 273.15; ratio = vp / TK                       # ideal PTAT: constant
lsb = 1.215 / 256
res = lsb / slope                                       # degC per LSB
# 1-point calibration at 27 C assuming ideal PTAT (V/T const): temperature error over range
k27 = np.argmin(abs(T - 27)); Test = vp / ratio[k27] - 273.15; terr = Test - T

os.makedirs(os.path.join(H, "plots"), exist_ok=True)
fig, ax = plt.subplots(1, 3, figsize=(13, 3.6))
ax[0].plot(T, vp * 1e3); ax[0].set(xlabel="T [°C]", ylabel="VPTAT [mV]", title=f"VPTAT: {slope*1e3:.3f} mV/°C (tt)")
ax[1].plot(T, nonlin * 1e3); ax[1].set(xlabel="T [°C]", ylabel="mV", title="Deviation from straight line")
ax[2].plot(T, terr); ax[2].set(xlabel="T [°C]", ylabel="°C", title="Temp. error, 1-point cal. at 27 °C (ideal PTAT)")
for a in ax: a.grid(alpha=0.3)
fig.tight_layout(); fig.savefig(os.path.join(H, "plots", "ptat.png"), dpi=90)

ok = lambda c: "✅" if c else "❌"
rows = [
    ("B10", "VPTAT at 27 °C", f"{vptat:.4f} V", "0.5 … 0.7 V", ok(0.5 <= vptat <= 0.7), "1"),
    ("—", "VBG change from adding the branch", f"{dvb_branch*1e6:.3f} µV", "< 100 µV", ok(abs(dvb_branch) < 1e-4), "1"),
    ("—", "VBG change with vptat loaded by 100 kΩ", f"{dvb_load*1e6:.3f} µV", "< 100 µV", ok(abs(dvb_load) < 1e-4), "1"),
    ("—", "Bandgap loop phase margin with the branch", f"{pm:.1f}° (fu {fu/1e6:.2f} MHz)", "≥ 60°", ok(pm >= 60), "1"),
    ("B11", "VPTAT slope, −40…125 °C (tt only)", f"{slope*1e3:.3f} mV/°C", "≥ 1.8 mV/°C", ok(slope >= 1.8e-3), "2 (early)"),
    ("—", "Max deviation from a straight line", f"{abs(nonlin).max()*1e3:.2f} mV", "—", "", "2 (early)"),
    ("B12", "Resolution with the 8-bit ADC (LSB 4.75 mV)", f"{res:.2f} °C/LSB", "≤ 2.7 °C/LSB", ok(res <= 2.7), "2 (early)"),
    ("B13", "1-point (27 °C) calibration error, tt, ideal-PTAT model", f"{abs(terr).max():.2f} °C", "≤ ±5 °C", ok(abs(terr).max() <= 5), "2 (early)"),
]
md = ["# Stage 4 — ptat_out results", "", "tt corner, VDPWR 1.80 V. Generated by `report.py` (`./run.sh`).", "",
      "| Spec | Quantity | Result | Target | | Phase |", "|---|---|---|---|---|---|"]
md += [f"| {a} | {b} | {c} | {d_} | {e} | {f} |" for a, b, c, d_, e, f in rows]
md += ["", f"VPTAT range −40…125 °C: {vp.min():.3f} … {vp.max():.3f} V (inside the ADC range 0 … 1.215 V).", "",
       "![ptat](plots/ptat.png)", ""]
open(os.path.join(H, "results.md"), "w").write("\n".join(md))
print("\n".join(md))
