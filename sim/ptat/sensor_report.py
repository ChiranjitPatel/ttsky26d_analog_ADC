#!/usr/bin/env python3
"""Phase 2 summary for the temperature sensor (VPTAT / VBG over -40...125 C): corners and Monte Carlo.
Reads ../out/corners/tb_ptat_p2/<run>/temp_p2.dat and writes sensor.md + plots/sensor.png.
Model of the measurement: code ~ 256 * VPTAT / VREF, VREF ~ VBG (internal reference). Calibration:
one point at 27 C, assuming ideal PTAT behaviour (ratio proportional to absolute temperature):
    T_est = (27 + 273.15) * r(T) / r(27 C) - 273.15
The error T_est - T is evaluated on the simulated ratio (no ADC quantization; that adds +-1.2 C).
"""
import csv, glob, os, sys
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

def runs(name):
    out = []
    for d in sorted(glob.glob(f"../out/corners/{name}/*/temp_p2.dat")):
        a = np.loadtxt(d, skiprows=1)
        T, vp, vb = a[:, 0], a[:, 1], a[:, 2]
        if not (0.5 < vb[len(vb) // 2] < 2):
            continue
        r = vp / vb
        r27 = np.interp(27, T, r)
        test = (27 + 273.15) * r / r27 - 273.15
        slope = np.polyfit(T, vp, 1)[0]
        out.append(dict(tag=os.path.basename(os.path.dirname(d)), T=T, err=test - T, slope=slope,
                        vp27=np.interp(27, T, vp), vb27=np.interp(27, T, vb)))
    return out
cor, mc = runs("tb_ptat_p2"), runs("tb_ptat_p2_mc")
L = ["# Temperature sensor — Phase 2 (generated by sensor_report.py)", "",
     "Error after a 1-point calibration at 27 °C with an ideal-PTAT model, on VPTAT/VBG (ADC quantization ±1.2 °C not included).", ""]
for title, rs in (("Corners (7 corners × 3 supplies)", cor), ("Monte Carlo (mismatch, tt, per seed)", mc)):
    if not rs:
        continue
    e = np.array([np.abs(r["err"]).max() for r in rs]); sl = np.array([r["slope"] for r in rs]) * 1e3
    vp = np.array([r["vp27"] for r in rs])
    L += [f"## {title}: {len(rs)} runs", "",
          "| Quantity | min | max | mean | σ |", "|---|---|---|---|---|",
          f"| VPTAT at 27 °C (V) | {vp.min():.4f} | {vp.max():.4f} | {vp.mean():.4f} | {vp.std(ddof=1)*1e3:.1f} mV |",
          f"| VPTAT slope (mV/°C) | {sl.min():.3f} | {sl.max():.3f} | {sl.mean():.3f} | {sl.std(ddof=1):.3f} |",
          f"| worst temperature error over −40…125 °C (°C) | {e.min():.2f} | {e.max():.2f} | {e.mean():.2f} | {e.std(ddof=1):.2f} |", ""]
open("sensor.md", "w").write("\n".join(L) + "\n")
fig, ax = plt.subplots(1, 2, figsize=(11, 4)); fig.patch.set_facecolor("white")
for i, (rs, t) in enumerate(((cor, "corners"), (mc, "Monte Carlo seeds"))):
    for r in rs:
        ax[i].plot(r["T"], r["err"], lw=0.8, alpha=0.7)
    ax[i].set(xlabel="temperature [°C]", ylabel="error after 1-point cal. [°C]", title=f"Temperature error, {t}")
    ax[i].grid(alpha=0.3); ax[i].axhline(5, color="r", lw=0.6, ls="--"); ax[i].axhline(-5, color="r", lw=0.6, ls="--")
fig.tight_layout(); os.makedirs("plots", exist_ok=True); fig.savefig("plots/sensor.png", dpi=110, facecolor="white")
print("\n".join(L))
