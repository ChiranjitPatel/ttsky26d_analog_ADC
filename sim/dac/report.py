#!/usr/bin/env python3
"""Stage 8 report: cap_dac transfer over all 256 codes (ideal vref/vcm/vin), DNL/INL, hold check."""
import os, re
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
H = os.path.dirname(os.path.abspath(__file__)); O = os.path.join(H, "..", "out", "dac")
d = np.loadtxt(os.path.join(O, "dac.dat"), skiprows=1); t, v = d[:, 0], d[:, 1]
codes = np.arange(256)
vk = np.array([v[np.argmin(abs(t - (k * 1e-6 + 0.95e-6)))] for k in codes])
LSB = 1.215 / 256
gain = (vk[255] - vk[0]) / 255; off = vk[0]
dnl = np.diff(vk) / gain - 1; inl = (vk - off) / gain - codes
# settling: value 0.1 us into the hold phase vs end of the hold phase, all codes
v01 = np.array([v[np.argmin(abs(t - (k * 1e-6 + 0.5e-6)))] for k in codes])
settle = abs(v01 - vk).max()
h = np.loadtxt(os.path.join(O, "hold.dat"), skiprows=1); th, vh = h[:, 0], h[:, 1]
drift = vh[np.argmin(abs(th - 50e-6))] - vh[np.argmin(abs(th - 0.5e-6))]
iref = abs(float(re.search(r"^iref\s*=\s*(\S+)", open(os.path.join(O, "tb_dac.log")).read(), re.M).group(1)))
os.makedirs(os.path.join(H, "plots"), exist_ok=True)
fig, ax = plt.subplots(1, 3, figsize=(14, 3.6))
ax[0].plot(codes, vk); ax[0].set(xlabel="code", ylabel="vtop − vcm [V]", title=f"Transfer: gain {gain/LSB:.5f}, offset {off*1e3:.3f} mV")
ax[1].plot(codes[1:], dnl); ax[1].set(xlabel="code", ylabel="DNL [LSB]", title=f"DNL (max {abs(dnl).max():.3f} LSB)")
ax[2].plot(codes, inl); ax[2].set(xlabel="code", ylabel="INL [LSB]", title=f"INL (max {abs(inl).max():.3f} LSB)")
for a in ax: a.grid(alpha=0.3)
fig.tight_layout(); fig.savefig(os.path.join(H, "plots", "dac.png"), dpi=90)
ok = lambda c: "✅" if c else "❌"
md = ["# Stage 8 — cap_dac results", "",
      "tt, 27 °C, 1.8 V; ideal VREF (1.215 V), vcm and VIN = 0 V; reltol 1e-5. Generated by `report.py`.", "",
      "| Spec | Quantity | Result | Target | | Phase |", "|---|---|---|---|---|---|",
      f"| — | Gain (vs ideal VREF/256 per code) / offset | {gain/LSB:.5f} / {off*1e3:+.3f} mV | — | | 1 |",
      f"| A4 (DAC part) | DNL, all codes (ideal caps) | {abs(dnl).max():.4f} LSB | ≤ 0.5 LSB | {ok(abs(dnl).max() <= 0.5)} | 1 |",
      f"| A5 (DAC part) | INL, all codes (ideal caps) | {abs(inl).max():.4f} LSB | ≤ 1 LSB | {ok(abs(inl).max() <= 1)} | 1 |",
      f"| — | Settling: change between 0.1 µs and 0.55 µs into the hold phase | {settle*1e6:.1f} µV | ≤ 0.5 LSB | {ok(settle <= 0.5*LSB)} | 1 |",
      f"| — | Top-plate hold drift over 50 µs (code 127) | {drift*1e6:+.1f} µV | ≪ 0.5 LSB (slow-clock modes) | {ok(abs(drift) < 0.1*LSB)} | 1 |",
      f"| — | Average VREF current (code sweep, 1 conversion-step per µs) | {iref*1e6:.2f} µA | — | | 1 |",
      "| A13 | Mismatch-induced DNL σ (Monte Carlo) | Phase 2 | ≤ 0.25 LSB | | 2 |",
      "", "![dac](plots/dac.png)", ""]
open(os.path.join(H, "results.md"), "w").write("\n".join(md)); print("\n".join(md))
