#!/usr/bin/env python3
"""A13: DNL/INL of the cap DAC from the Monte Carlo bit capacitances (tb_dac_mc.spice via tools/run_corners.py).
Level of code k: L(k) = sum_i b_i C_i (the top-plate attenuation and the termination cap only scale the gain).
DNL(k) = (L(k) - L(k-1)) / LSB - 1 and INL(k) = (L(k) - k LSB) / LSB with the end-point LSB = L(255) / 255.
Writes mc.md."""
import csv, os
import numpy as np
H = os.path.dirname(os.path.abspath(__file__))
rows = list(csv.DictReader(open(os.path.join(H, "..", "out", "corners", "tb_dac_mc", "results.csv"))))
C = np.array([[float(r[f"c{i}"]) for i in range(8)] for r in rows if r.get("c7")])
k = np.arange(256)
B = (k[:, None] >> np.arange(8)) & 1                     # 256 x 8
L = C @ B.T                                              # seeds x 256
lsb = L[:, -1:] / 255
dnl = np.diff(L, axis=1) / lsb - 1                       # seeds x 255 (code k-1 -> k)
inl = (L - k * lsb) / lsb
mid = dnl[:, 127]                                        # 127 -> 128, the MSB transition
out = [f"# Cap DAC mismatch Monte Carlo (A13, Phase 2)\n",
       f"{len(C)} seeds, `tt_mm` (sky130 MIM mismatch: σ = 2.8 % / √(W L m)), unit cap 2 × 1.65 µm "
       f"({C[:, 0].mean() * 1e15:.2f} fF mean). Generated by `dac_mc_stats.py` from `tb_dac_mc.spice`.\n",
       "| Quantity | Result | Target |", "|---|---|---|",
       f"| DNL σ at the MSB transition (127 → 128) | {mid.std(ddof=1):.3f} LSB | A13: ≤ 0.25 LSB |",
       f"| DNL σ, worst code | {dnl.std(axis=0, ddof=1).max():.3f} LSB (code {int(dnl.std(axis=0, ddof=1).argmax()) + 1}) | ≤ 0.25 LSB |",
       f"| max \\|DNL\\| per chip: median / 95th pct / worst | {np.median(abs(dnl).max(1)):.3f} / "
       f"{np.percentile(abs(dnl).max(1), 95):.3f} / {abs(dnl).max():.3f} LSB | A4 (tt, no mismatch): ±0.5 LSB |",
       f"| chips with any \\|DNL\\| > 0.5 LSB | {int((abs(dnl).max(1) > 0.5).sum())} / {len(C)} | |",
       f"| chips with a missing code (DNL ≤ −1) | {int((dnl.min(1) <= -1).sum())} / {len(C)} | 0 |",
       f"| max \\|INL\\| per chip: median / 95th pct / worst | {np.median(abs(inl).max(1)):.3f} / "
       f"{np.percentile(abs(inl).max(1), 95):.3f} / {abs(inl).max():.3f} LSB | A5 (tt): ±1 LSB |"]
txt = "\n".join(out)
print(txt)
open(os.path.join(H, "mc.md"), "w").write(txt + "\n")
