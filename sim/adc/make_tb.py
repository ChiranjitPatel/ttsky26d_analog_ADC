#!/usr/bin/env python3
"""I2 testbench generator: adc_core (DAC + comparator + vcm_gen + std-cell SAR logic), ideal VREF.

Usage: make_tb.py [--real-ref] name vin1 vin2 ...   (or: make_tb.py [--real-ref] name --sine N M amp offset)
--real-ref (integration I3): VREF comes from bandgap_core -> vref_filt -> vref_buf instead of an ideal
source; conversions start at 30 us, after the filtered reference has settled.
Writes tb_<name>.spice. Each conversion takes 10 clocks (10 us at 1 MHz). VIN is an ideal source
behind 500 Ohm (pad model, no mux) that changes value right after each EOC, so it is stable during
the next SAMPLE cycle. start stays high (back-to-back conversions).
"""
import math, sys
real_ref = "--real-ref" in sys.argv
if real_ref: sys.argv.remove("--real-ref")
name = sys.argv[1]
if sys.argv[2] == "--sine":
    N, M, amp, off = int(sys.argv[3]), int(sys.argv[4]), float(sys.argv[5]), float(sys.argv[6])
    vins = [off + amp * math.sin(2 * math.pi * M * k / N) for k in range(N)]
else:
    vins = [float(x) for x in sys.argv[2:]]
T, TCONV = 1e-6, 10e-6
T0 = 32e-6 if real_ref else 3e-6   # first SAMPLE (start goes high 1.5 us earlier)
pwl = []
for k, v in enumerate(vins):
    t = max(T0 + k * TCONV - 1.5e-6, 0)   # change during the previous conversion's EOC/bit phase
    t_next = T0 + (k + 1) * TCONV - 1.5e-6
    # a step: hold v until just before the next change (a single point per value would make PWL ramp)
    pwl.append(f"{t:.9g} {v:.9g} {t_next - 1e-9:.9g} {v:.9g}")
tstop = T0 + len(vins) * TCONV + 2e-6
L = [f"* I2 — adc_core with ideal VREF: {len(vins)} conversions (generated by make_tb.py)",
     ".lib /usr/local/share/pdk/sky130A/libs.tech/ngspice/sky130.lib.spice tt",
     ".include /usr/local/share/pdk/sky130A/libs.ref/sky130_fd_sc_hd/spice/sky130_fd_sc_hd.spice",
     ".include ../out/netlist/bias_gen.spice", ".include ../out/netlist/sar_logic.spice",
     ".include ../out/netlist/adc_core.spice",
     *([".include ../out/netlist/bandgap_core.spice", ".include ../out/netlist/vref_filt.spice",
        ".include ../out/netlist/vref_buf.spice"] if real_ref else []), ".temp 27",
     ".options reltol=1e-5 abstol=1e-12 vntol=1e-7 chgtol=1e-16",
     "VDD vdd 0 1.8", "VPD pd 0 0", "xb vdd 0 pd nbias pbias bias_gen",
     *(["xbg vdd 0 pbias pd vbg vgp bandgap_core", "xf 0 vbg vbg_f vref_filt", "VEN en 0 1.8",
        "xbuf vdd 0 nbias en vbg_f vref vref_buf"] if real_ref else ["VREF vref 0 1.215"]),
     "VCLK clk 0 pulse(0 1.8 0.5u 0.5n 0.5n 0.5u 1u)",
     "VRST rst_n 0 pwl(0 0 1.5u 0 1.501u 1.8)",
     f"VST start 0 pwl(0 0 {T0-1.6e-6:.6g} 0 {T0-1.599e-6:.6g} 1.8)" if real_ref else "VST start 0 1.8", "VMODE mode 0 0", "VZ z 0 0",
     "VIN vsrc 0 pwl(" + " ".join(pwl) + ")", "RPAD vsrc vadc_pad 500", "CPAD vadc_pad 0 5p",
     "x1 vdd 0 pbias vref vadc_pad clk rst_n start mode z z z z z z z z z z " + " ".join(f"d{i}" for i in range(8)) + " eoc cmp adc_core",
     ".control", "set wr_singlescale", "set wr_vecnames",
     "save v(clk) v(eoc) v(vsrc) v(x1.vtop) v(x1.vcm) v(x1.smpt) v(vref) " + " ".join(f"v(d{i})" for i in range(8)),
     f"tran 2n {tstop:.6g}", f"wrdata ../out/adc/{name}.dat v(clk) v(eoc) v(vsrc) v(x1.vtop) v(x1.vcm) v(x1.smpt) " + " ".join(f"v(d{i})" for i in range(8)) + " v(vref)",
     "quit", ".endc", ".end"]
open(f"tb_{name}.spice", "w").write("\n".join(L) + "\n")
open(f"../out/adc/{name}_vin.txt", "w").write("\n".join(f"{v:.9g}" for v in vins) + "\n")
print(f"tb_{name}.spice: {len(vins)} conversions, tstop {tstop*1e6:.0f} us")
