#!/usr/bin/env python3
"""Phase 2 summary for the VREF chain (bandgap -> vref_filt -> vref_buf, + vref_sel, pad, DAC-like load).
Reads ../out/corners/tb_vref/ (tools/run_corners.py) and writes corners.md. Run from sim/vref after:
    ../../tools/run_corners.py tb_vref.spice --corners tt,ff,ss,fs,sf --temps=-40,27,125 --vdd 1.62,1.8,1.98
Per run: PSRR at vbg_f (B7), buffer offset, DAC-like load error at the end of each bit cycle (<= 0.5 LSB),
startup time of vref (1 % after the 1 us ramp), buffer current.
"""
import csv, os
import numpy as np

base = "../out/corners/tb_vref"
rows = list(csv.DictReader(open(f"{base}/results.csv")))
f = lambda r, k: float(r[k]) if r.get(k) not in (None, "") else float("nan")
TL = 150e-6                                   # DAC-like load starts here (tb_vref.spice)
for r in rows:
    r["T"], r["V"] = int(r["temp"]), float(r["vdd"])
    d = os.path.join(base, r["tag"], "tran.dat")
    r["err"] = r["tstart"] = float("nan")
    if os.path.exists(d):
        a = np.loadtxt(d, skiprows=1); t, vr = a[:, 0], a[:, 1]
        pre = vr[np.argmin(abs(t - (TL - 0.1e-6)))]
        r["err"] = max(abs(vr[np.argmin(abs(t - (TL + 0.87e-6 + c * 1e-6)))] - pre) for c in range(10))
        m = t < TL - 1e-6
        bad = np.where(abs(vr[m] - pre) > 0.01 * pre)[0]
        r["tstart"] = t[m][bad[-1] + 1] - 1e-6 if len(bad) else 0.0
        r["vref"] = pre
    r["offs"] = f(r, "offs")
fails = [r["tag"] for r in rows if r["rc"] != "0"]
L = ["# VREF chain — Phase 2 corners (generated by corners_report.py)", "",
     f"{len(rows)} runs: corners tt/ff/ss/fs/sf × −40/27/125 °C × VDPWR 1.62/1.80/1.98 V. Failed runs: {len(fails)}"
     + (f" ({', '.join(fails)})" if fails else "") + ".", "",
     "| Quantity | worst | where | Target | |", "|---|---|---|---|---|"]
def worst(key, fn=max, absval=False):
    vals = [(abs(r[key]) if absval else r[key], r["tag"]) for r in rows if r.get(key) == r.get(key)]
    return fn(vals)
for k in ("pf_dc", "pf_1m"):
    for r in rows: r[k] = f(r, k)
w_dc, w_1m = worst("pf_dc", min), worst("pf_1m", min)
w_err, w_ts, w_off = worst("err"), worst("tstart"), worst("offs", absval=True)
ib = [f(r, "ibuf") for r in rows]
L += [f"| B7: PSRR at vbg_f, DC | {w_dc[0]:.1f} dB | {w_dc[1]} | ≥ 40 dB | {'✅' if w_dc[0] >= 40 else '❌'} |",
      f"| B7: PSRR at vbg_f, 1 MHz | {w_1m[0]:.1f} dB | {w_1m[1]} | ≥ 20 dB | {'✅' if w_1m[0] >= 20 else '❌'} |",
      f"| DAC-like load: error at the end of a bit cycle | {w_err[0]*1e6:.1f} µV | {w_err[1]} | ≤ 0.5 LSB = 2.4 mV | {'✅' if w_err[0] <= 2.4e-3 else '❌'} |",
      f"| Startup: vref within 1 % | {w_ts[0]*1e6:.1f} µs | {w_ts[1]} | ≤ 100 µs | {'✅' if w_ts[0] <= 100e-6 else '❌'} |",
      f"| Buffer offset (vref − vbg_f) | {w_off[0]*1e3:.2f} mV | {w_off[1]} | — | |",
      f"| Buffer current | {min(ib)*1e6:.2f} … {max(ib)*1e6:.2f} µA | | — | |",
      f"| VREF (internal, before the load) | {min(r['vref'] for r in rows):.4f} … {max(r['vref'] for r in rows):.4f} V | | — | |"]
open("corners.md", "w").write("\n".join(L) + "\n")
print("\n".join(L))
