#!/usr/bin/env python3
"""Phase 2 summary for bias_gen: reads ../out/corners/tb_bias/results.csv (tools/run_corners.py) and writes
corners.md + plots/corners.png. Run from sim/bias after:
    ../../tools/run_corners.py tb_bias.spice --corners tt,ff,ss,fs,sf --temps=-40,27,125 --vdd 1.62,1.8,1.98
"""
import csv, os
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

rows = list(csv.DictReader(open("../out/corners/tb_bias/results.csv")))
f = lambda r, k: float(r[k]) if r.get(k) not in (None, "") else float("nan")
for r in rows:
    r["T"] = int(r["temp"]); r["V"] = float(r["vdd"])
    r["isink"] = f(r, "isink"); r["isrc"] = f(r, "isrc"); r["icore"] = f(r, "icore"); r["ipd"] = f(r, "ipd")
    r["ist_fast"] = f(r, "ist_fast"); r["ist_slow"] = f(r, "ist_slow")
    r["v50"] = f(r, "t50_slow") / 100e-6 * r["V"]          # slow ramp 0 -> VDD in 100 us
    r["sumin"] = min(f(r, "sumin_fast"), f(r, "sumin_slow"))
    r["su_ok"] = abs(r["ist_fast"] / r["isink"] - 1) < 0.01 and abs(r["ist_slow"] / r["isink"] - 1) < 0.01

bad = [r for r in rows if r["rc"] != "0" or r["isink"] != r["isink"]]
# the .op value must agree with the DC supply sweep at the same VDPWR (catches a non-converged .op)
sweep_key = {1.62: "isink162", 1.8: "isink180", 1.98: "isink198"}
op_bad = [r for r in rows if abs(r["isink"] / f(r, sweep_key[r["V"]]) - 1) > 0.01]
nom = {r["corner"] + str(r["T"]): r for r in rows if r["V"] == 1.8}
isk = [r["isink"] for r in rows]; isr = [r["isrc"] for r in rows]
L = ["# bias_gen — Phase 2 corners (generated by corners_report.py)", "",
     f"{len(rows)} runs: corners tt/ff/ss/fs/sf × −40/27/125 °C × VDPWR 1.62/1.80/1.98 V. "
     f"Failed runs: {len(bad)}. Runs where the .op current differs from the DC sweep by > 1 %: {len(op_bad)}"
     + (" (" + ", ".join(r["tag"] for r in op_bad) + ")" if op_bad else "") + ".", "",
     "## Unit currents at VDPWR = 1.80 V (µA)", "",
     "| corner | sink −40 °C | sink 27 °C | sink 125 °C | source −40 °C | source 27 °C | source 125 °C |",
     "|---|---|---|---|---|---|---|"]
for c in "tt ff ss fs sf".split():
    L.append(f"| {c} | " + " | ".join(f"{nom[c+str(T)]['isink']*1e6:.3f}" for T in (-40, 27, 125)) + " | "
             + " | ".join(f"{nom[c+str(T)]['isrc']*1e6:.3f}" for T in (-40, 27, 125)) + " |")
lin = []
for c in "tt ff ss fs sf".split():
    for T in (-40, 27, 125):
        g = {r["V"]: r["isink"] for r in rows if r["corner"] == c and r["T"] == T}
        lin.append((abs(g[1.98] - g[1.62]) / g[1.8], c, T))
worst_lin = max(lin)
su_fail = [r for r in rows if not r["su_ok"]]
v50 = max(rows, key=lambda r: r["v50"])
L += ["", "## Summary over all 45 runs", "",
      "| Quantity | min | max | Note |", "|---|---|---|---|",
      f"| Unit sink (nfet 2/2) | {min(isk)*1e6:.3f} µA | {max(isk)*1e6:.3f} µA | spread {max(isk)/min(isk):.2f}× |",
      f"| Unit source (pfet_lvt 2/2) | {min(isr)*1e6:.3f} µA | {max(isr)*1e6:.3f} µA | spread {max(isr)/min(isr):.2f}× |",
      f"| bias_gen own current | {min(r['icore'] for r in rows)*1e6:.2f} µA | {max(r['icore'] for r in rows)*1e6:.2f} µA | |",
      f"| Power-down supply current | {min(r['ipd'] for r in rows)*1e9:.2f} nA | {max(r['ipd'] for r in rows)*1e9:.2f} nA | |",
      f"| Line: sink change 1.62–1.98 V | | {worst_lin[0]*100:.1f} % | worst at {worst_lin[1]}, {worst_lin[2]} °C (target < 10 %) |",
      f"| Startup (1 µs and 100 µs ramps reach the DC current within 1 %) | | | {len(rows)-len(su_fail)}/{len(rows)} runs |",
      f"| Slow ramp: VDPWR when the sink reaches 0.5 µA | {min(r['v50'] for r in rows):.2f} V | {v50['v50']:.2f} V | worst at {v50['corner']}, {v50['T']} °C, {v50['V']} V (must be < 1.62 V) |",
      f"| Lowest `su` during the ramps | {min(r['sumin'] for r in rows):.2f} V | | junction clamp; startup unaffected |"]
if su_fail:
    L += ["", "Startup failures: " + ", ".join(r["tag"] for r in su_fail)]
open("corners.md", "w").write("\n".join(L) + "\n")

fig, ax = plt.subplots(1, 2, figsize=(10, 4)); fig.patch.set_facecolor("white")
for c, col in zip("tt ff ss fs sf".split(), ["k", "C3", "C0", "C2", "C1"]):
    for i, key in enumerate(("isink", "isrc")):
        ax[i].plot([-40, 27, 125], [nom[c + str(T)][key] * 1e6 for T in (-40, 27, 125)], "o-", color=col, label=c)
for i, t in enumerate(("unit sink nfet_01v8 2/2", "unit source pfet_01v8_lvt 2/2")):
    ax[i].set_title(t + " (VDPWR 1.8 V)"); ax[i].set_xlabel("temperature [°C]"); ax[i].set_ylabel("current [µA]")
    ax[i].grid(alpha=0.3); ax[i].legend()
fig.tight_layout(); os.makedirs("plots", exist_ok=True); fig.savefig("plots/corners.png", dpi=110, facecolor="white")
print("\n".join(L))
