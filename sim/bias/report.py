#!/usr/bin/env python3
"""Stage 1 report: parse tb_bias results, write results.md and plots/bias.png."""
import os, re
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

H = os.path.dirname(os.path.abspath(__file__))
O = os.path.join(H, "..", "out", "bias")
log = open(os.path.join(O, "tb_bias.log")).read()
val = lambda k: float(re.search(rf"^{k}\s*=\s*(\S+)", log, re.M).group(1))
ld = lambda f: np.loadtxt(os.path.join(O, f), skiprows=1)

isink, isrc, icore, ipd = val("isink"), val("isrc"), val("icore"), val("ipd")
i162, i198 = val("isink162"), val("isink198")
line_pct = (i198 - i162) / isink * 100

def settle(f, ramp_end):
    t, i = ld(f)[:, 0], ld(f)[:, 1]
    bad = np.where(abs(i - i[-1]) > 0.01 * i[-1])[0]
    return t, i, ld(f)[:, 4], t[bad[-1] + 1] - ramp_end
tf, i_f, su_f, ts_fast = settle("startup.dat", 1e-6)
ts_, i_s, su_s, ts_slow = settle("startup_slow.dat", 100e-6)
k50 = np.argmax((ts_ > 1e-6) & (i_s > 0.5 * i_s[-1])); v_start = 1.8 * ts_[k50] / 100e-6
sv = ld("sink_vout.dat"); vout, iout = sv[:, 0], -sv[:, 1]
i09 = iout[np.argmin(abs(vout - 0.9))]
v_comp = vout[np.argmax(iout >= 0.95 * i09)]
ln = ld("line.dat")

os.makedirs(os.path.join(H, "plots"), exist_ok=True)
fig, ax = plt.subplots(1, 3, figsize=(13, 3.6))
ax[0].plot(ln[:, 0], ln[:, 1] * 1e6, label="unit nfet sink"); ax[0].plot(ln[:, 0], ln[:, 2] * 1e6, label="unit pfet_lvt source")
ax[0].axvspan(1.62, 1.98, alpha=0.1); ax[0].set(xlabel="VDPWR [V]", ylabel="I [uA]", title="Line regulation"); ax[0].legend(fontsize=7)
ax[1].plot(tf * 1e6, i_f * 1e6, label="I sink"); ax[1].plot(tf * 1e6, su_f, label="v(su) [V]")
ax[1].set(xlabel="t [us]", title="Startup, 1 us ramp", xlim=(0, 5)); ax[1].legend(fontsize=7)
ax[2].plot(ts_ * 1e6, i_s * 1e6, label="I sink"); ax[2].plot(ts_ * 1e6, su_s, label="v(su) [V]")
ax[2].set(xlabel="t [us]", title="Startup, 100 us ramp"); ax[2].legend(fontsize=7)
for a in ax: a.grid(alpha=0.3)
fig.tight_layout(); fig.savefig(os.path.join(H, "plots", "bias.png"), dpi=90)

ok = lambda c: "✅" if c else "❌"
rows = [
    ("Unit sink current (nfet_01v8 W=2 L=2, Vds 0.9 V)", f"{isink*1e6:.3f} µA", "1 µA", ok(abs(isink - 1e-6) < 0.05e-6)),
    ("Unit source current (pfet_01v8_lvt W=2 L=2, Vsd 0.9 V)", f"{isrc*1e6:.3f} µA", "1 µA", ok(abs(isrc - 1e-6) < 0.05e-6)),
    ("bias_gen own supply current", f"{icore*1e6:.2f} µA", "—", ""),
    ("Line: sink change over 1.62–1.98 V", f"{line_pct:.1f} %", "< 10 % (Phase 2 target)", ok(line_pct < 10)),
    ("Sink compliance (95 % of current)", f"{v_comp:.2f} V", "—", ""),
    ("Power-down supply current", f"{ipd*1e9:.2f} nA", "—", ""),
    ("Startup, 1 µs ramp: settled to 1 % after ramp end", f"{ts_fast*1e6:.2f} µs", "starts from 0 V", ok(ts_fast < 20e-6)),
    ("Startup, 100 µs ramp: VDPWR when current reaches 50 %", f"{v_start:.2f} V", "starts before VDPWR = 1.62 V", ok(v_start < 1.62)),
    ("Startup node v(su) when running", f"{su_f[-1]*1e3:.0f} mV", "MS1 off", ok(su_f[-1] < 0.1)),
]
md = ["# Stage 1 — bias_gen results", "", "Phase 1: tt, 27 °C, VDPWR 1.80 V (line sweep shown for information).",
      "Generated by `report.py` from `tb_bias.spice`.", "",
      "| Quantity | Result | Target | |", "|---|---|---|---|"]
md += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in rows]
md += ["", "![bias](plots/bias.png)", ""]
open(os.path.join(H, "results.md"), "w").write("\n".join(md))
print("\n".join(md))
