#!/usr/bin/env python3
"""M1 post-layout report: schematic vs R+C-extracted layout. Writes results.md and plots/m1_postlayout.png."""
import os, re
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "out", "m1")
DUTS = ("sch", "rc")

def res(dut, test):
    d = {}
    p = os.path.join(OUT, f"{dut}_{test}.log")
    if not os.path.exists(p):
        return d
    for line in open(p):
        if line.startswith("RES "):
            t = line.split()
            d[t[1]] = {t[i]: float(t[i + 1]) for i in range(2, len(t) - 1, 2)
                       if re.match(r"^-?[\d.]+(e[-+]?\d+)?$", t[i + 1], re.I)}
    return d
R = {d: {**res(d, "op"), **res(d, "ac"), **res(d, "tran")} for d in DUTS}
def g(d, k, q, scale=1.0):
    try:
        return R[d][k][q] * scale
    except KeyError:
        return float("nan")

rows = [  # label, key, quantity, scale, unit, format, target, pass(sch_or_rc value) or None
    ("VBG", "A_internal", "vbg", 1, "V", "{:.4f}", "1.18–1.25 V (B1)", lambda v: 1.18 <= v <= 1.25),
    ("vbg_f (filter output)", "A_internal", "vbg_f", 1, "V", "{:.4f}", "= VBG", None),
    ("VREF (internal)", "A_internal", "vref", 1, "V", "{:.4f}", "≈ VBG", None),
    ("VPTAT", "A_internal", "vptat", 1, "V", "{:.4f}", "—", None),
    ("Supply current, normal", "A_internal", "idd", -1e6, "µA", "{:.2f}", "—", None),
    ("VREF_OE = 1: ua[1] pin, 10 MΩ DMM", "B_dmm", "pin", 1, "V", "{:.4f}", "VREF − ≤ 2 mV", None),
    ("VREF_OE = 1: vref", "B_dmm", "vref", 1, "V", "{:.4f}", "—", None),
    ("REF_SEL = 1, 1.5 V on ua[1]: vref", "C_extref", "vref", 1, "V", "{:.4f}", "1.5000 V", lambda v: abs(v - 1.5) < 1e-3),
    ("REF_SEL = 1: supply current", "C_extref", "idd", -1e6, "µA", "{:.2f}", "buffer off", None),
    ("BG_PD = 1: supply current (transient, 299 µs)", "tran", "idd_pd", -1e9, "nA", "{:.2f}", "≤ 1000 nA (B8)", lambda v: v <= 1000),
    ("PSRR vbg_f, DC (B7)", "psrr", "vbg_f_dc", 1, "dB", "{:.1f}", "≥ 40 dB", lambda v: v >= 40),
    ("PSRR vbg_f, 1 MHz (B7)", "psrr", "vbg_f_1m", 1, "dB", "{:.1f}", "≥ 20 dB", lambda v: v >= 20),
    ("PSRR vref, DC", "psrr", "vref_dc", 1, "dB", "{:.1f}", "—", None),
    ("PSRR vref, 1 MHz", "psrr", "vref_1m", 1, "dB", "{:.1f}", "—", None),
    ("Startup from 0 V: vref within 1 %", "tran", "t_up", 1e6, "µs", "{:.1f}", "≤ 100 µs", lambda v: v <= 100),
    ("ua[1] pin at 249 µs (VREF_OE from 150 µs)", "tran", "pin_end", 1, "V", "{:.4f}", "≈ VREF", None),
    ("vref during BG_PD (299 µs)", "tran", "vref_pd", 1, "V", "{:.4f}", "not driven (CRES holds charge)", None),
    ("Restart after BG_PD: vref within 1 %", "tran", "t_re", 1e6, "µs", "{:.1f}", "≤ 100 µs after 300 µs", None),
]
md = ["# M1 post-layout results (schematic vs extracted layout)", "",
      "tt, 27 °C, VDPWR 1.80 V. Generated by `report.py` (`./run.sh`). The same testbenches run on the schematic top level",
      "(`layout/cells/m1_top_ref.spice`) and on the flat R+C extraction of the submission GDS (`layout/m1_pex.py`).",
      "The DUT is driven only through its pins; ua[1] pad model 5 pF + 500 Ω, DMM 10 MΩ ∥ 10 pF.", "",
      "| Quantity | Schematic | Layout (R+C) | Δ | Target | |", "|---|---|---|---|---|---|"]
for lab, k, q, sc, u, fmt, tgt, ok in rows:
    a, b = g("sch", k, q, sc), g("rc", k, q, sc)
    if k == "tran" and q == "t_re":
        a, b = a - 300, b - 300
    d = b - a
    mark = "" if ok is None or np.isnan(b) else ("✅" if ok(b) and (np.isnan(a) or ok(a)) else "❌")
    ds = ("{:+.2f}" if u in ("µA", "nA", "dB", "µs") else "{:+.1f} mV").format(d * (1 if u != "V" else 1e3))
    md.append(f"| {lab} | {fmt.format(a)} {u} | {fmt.format(b)} {u} | {ds} | {tgt} | {mark} |")
md += ["", "Restart time is measured from the release of BG_PD at 300 µs. The power-down current is taken from the",
       "transient: in power-down several nodes float, so the DC operating point is not unique.", ""]
# extraction summary from the m1_pex.py log, if present
ex = os.path.join(OUT, "extract.txt")
if os.path.exists(ex):
    md += ["## Extraction", "", "```", open(ex).read().strip(), "```", ""]
md += ["![m1 post-layout](plots/m1_postlayout.png)", ""]
open(os.path.join(HERE, "results.md"), "w").write("\n".join(md))

fig, ax = plt.subplots(1, 2, figsize=(12, 4.2)); fig.patch.set_facecolor("white")
for d, ls in (("sch", "-"), ("rc", "--")):
    f = os.path.join(OUT, f"{d}_tran.dat")
    if os.path.exists(f):
        x = np.loadtxt(f, skiprows=1)
        lab = "schematic" if d == "sch" else "layout R+C"
        ax[0].plot(x[:, 0] * 1e6, x[:, 3], ls, label=f"vref, {lab}")
        ax[0].plot(x[:, 0] * 1e6, x[:, 5], ls, label=f"ua[1] pin, {lab}")
    f = os.path.join(OUT, f"{d}_ac.dat")
    if os.path.exists(f):
        x = np.loadtxt(f, skiprows=1)
        lab = "schematic" if d == "sch" else "layout R+C"
        ax[1].semilogx(x[:, 0], x[:, 2], ls, label=f"vbg_f, {lab}")
        ax[1].semilogx(x[:, 0], x[:, 3], ls, label=f"vref, {lab}")
ax[0].set_xlabel("time [µs]"); ax[0].set_ylabel("V"); ax[0].grid(alpha=.3); ax[0].legend(fontsize=7)
ax[0].set_title("Startup (0–150 µs), VREF_OE = 1 from 150 µs, BG_PD 250–300 µs", fontsize=9)
ax[1].axhline(20, color="gray", lw=.8, ls=":"); ax[1].set_xlabel("frequency [Hz]"); ax[1].set_ylabel("PSRR [dB]")
ax[1].grid(alpha=.3, which="both"); ax[1].legend(fontsize=7); ax[1].set_title("PSRR", fontsize=9)
fig.tight_layout(); os.makedirs(os.path.join(HERE, "plots"), exist_ok=True)
fig.savefig(os.path.join(HERE, "plots", "m1_postlayout.png"), dpi=110, facecolor="white")
print("\n".join(md))
