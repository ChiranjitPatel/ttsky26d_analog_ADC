#!/usr/bin/env python3
"""M1 post-layout testbenches: the same tests on the schematic top level (layout/cells/m1_top_ref.spice)
and on the flat R+C-extracted layout (sim/out/layout/m1_rc/m1_rc.spice, from layout/m1_pex.py).

Writes sim/m1/tb_m1_<dut>_<test>.spice for dut in (sch, rc) and test in (op, ac, tran).
The DUT is driven only through its pins, as on the TT demo board:
  ui_in[3] BG_PD, ui_in[1] VREF_OE, uio_in[3] REF_SEL, ua[1] VREF pad.
ua[1] pad model (CLAUDE.md rule 2): 5 pF on the chip side, 500 Ohm to the pin; DMM 10 MOhm + 10 pF.
Internal nodes (vbg, vbg_f, vref, vptat) are probed by hierarchical name; their names differ between the
two netlists (see NODES).
"""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
TOP = "tt_um_chiranjitpatel_sar_adc"
NETS = {"sch": os.path.join(ROOT, "layout", "cells", "m1_top_ref.spice"),
        "rc": os.path.join(ROOT, "sim", "out", "layout", "m1_rc", "m1_rc.spice")}   # layout/m1_pex.py
NODES = {"sch": {"vbg": "xdut.vbg", "vbg_f": "xdut.vbg_f", "vref": "xdut.vref", "vptat": "xdut.vptat"},
         "rc": {"vbg": "xdut.bandgap_core_0.vbg", "vbg_f": "xdut.vref_filt_0.vbg_f", "vref": "xdut.vref_sel_0.vref",
                "vptat": "xdut.ptat_out_0.vptat"}}
PINS = {"VDPWR": "vdd", "VGND": "0", "ui_in[3]": "bgpd", "ui_in[1]": "oe", "uio_in[3]": "rs", "ua[1]": "pad"}

def ports(path):
    """Port list of the top .subckt (with '+' continuation lines)."""
    txt = open(path).read()
    m = re.search(rf"^\.subckt {re.escape(TOP)}\b(.*?)\n(?!\+)", txt, re.M | re.S)
    return m.group(1).replace("\n+", " ").split()

def tb(dut, test):
    p = ports(NETS[dut])
    conn = " ".join(PINS.get(x, "0" if x.startswith(("ui_in", "uio_in", "ena", "clk", "rst_n")) else f"nc_{re.sub(r'[^0-9a-z_]', '_', x)}")
                    for x in p)
    n = NODES[dut]
    nc = sorted({c for c in conn.split() if c.startswith("nc_")})
    s = [f"* M1 post-layout: {test} on the {dut} netlist (generated by sim/m1/make_tb.py), tt, 27 C, 1.8 V",
         ".lib /usr/local/share/pdk/sky130A/libs.tech/ngspice/sky130.lib.spice tt",
         f".include {NETS[dut]}", ".temp 27",
         ".options reltol=1e-5 abstol=1e-12 vntol=1e-7 chgtol=1e-16" if test != "tran" else
         ".options reltol=1e-4 abstol=1e-12 vntol=1e-6 method=gear",
         f"xdut {conn} {TOP}",
         "CPAD pad 0 5p", "RPAD pad pin 500", "CDMM pin 0 10p", "RDMM pin 0 10meg",
         "* unused pins (other analog pads, VGND-tied outputs): 1 GOhm to ground so they are not floating",
         *[f"R{c} {c} 0 1g" for c in nc]]
    out = f"../out/m1/{dut}_{test}"
    if test == "op":
        s += ["VDD vdd 0 1.8", "VPD bgpd 0 0", "VOE oe 0 0", "VRS rs 0 0", "VEXT ext 0 1.5", "SEXT ext pin rs 0 swx",
              ".model swx sw vt=0.9 vh=0.1 ron=1 roff=1e15",
              ".control", "set wr_singlescale", "set wr_vecnames",
              *[f"* mode {k}" for k in ()]]
        modes = [("A_internal", 0, 0, 0), ("B_dmm", 0, 1, 0), ("C_extref", 0, 0, 1.8), ("D_bgpd", 1.8, 0, 0)]
        for name, pd, oe, rs in modes:
            s += [f"alter VPD dc={pd}", f"alter VOE dc={1.8 if oe else 0}", f"alter VRS dc={rs}", "op",
                  f"echo RES {name} vbg $&v({n['vbg']}) vbg_f $&v({n['vbg_f']}) vref $&v({n['vref']}) "
                  f"vptat $&v({n['vptat']}) pin $&v(pin) idd $&i(VDD)"]
        s += ["quit", ".endc", ".end"]
    elif test == "ac":
        s += ["VDD vdd 0 dc 1.8 ac 1", "VPD bgpd 0 0", "VOE oe 0 0", "VRS rs 0 0",
              ".control", "set wr_singlescale", "set wr_vecnames", "ac dec 20 1 1e8",
              f"let p_vbg = -db(v({n['vbg']}))", f"let p_f = -db(v({n['vbg_f']}))", f"let p_ref = -db(v({n['vref']}))",
              f"wrdata {out}.dat p_vbg p_f p_ref",
              "meas ac pf_dc find p_f at=1", "meas ac pf_1m find p_f at=1e6",
              "meas ac pr_dc find p_ref at=1", "meas ac pr_1m find p_ref at=1e6",
              "echo RES psrr vbg_f_dc $&pf_dc vbg_f_1m $&pf_1m vref_dc $&pr_dc vref_1m $&pr_1m",
              "quit", ".endc", ".end"]
    else:
        # startup from 0 V (1 us ramp); VREF_OE at 150 us puts vref on the pad; BG_PD 250-300 us; re-start after
        s += ["VDD vdd 0 dc 0 pulse(0 1.8 0 1u 1u 1 2)", "VOE oe 0 dc 0 pulse(0 1.8 150u 10n 10n 1 2)",
              "VPD bgpd 0 dc 0 pulse(0 1.8 250u 10n 10n 50u 1)", "VRS rs 0 0",
              ".control", "set wr_singlescale", "set wr_vecnames", "save " + " ".join(
                  f"v({n[k]})" for k in ("vbg", "vbg_f", "vref", "vptat")) + " v(pin) i(VDD)",
              "tran 50n 450u uic",
              f"wrdata {out}.dat v({n['vbg']}) v({n['vbg_f']}) v({n['vref']}) v({n['vptat']}) v(pin)",
              f"meas tran vref_end find v({n['vref']}) at=149u",
              f"meas tran t_up when v({n['vref']})=0.99*vref_end rise=1",
              "meas tran pin_end find v(pin) at=249u",
              f"meas tran vref_pd find v({n['vref']}) at=299u",
              "meas tran idd_pd find i(VDD) at=299u",
              f"meas tran vref_re find v({n['vref']}) at=449u",
              f"meas tran t_re when v({n['vref']})=0.99*vref_re rise=last",
              "echo RES tran vref_end $&vref_end t_up $&t_up pin_end $&pin_end vref_pd $&vref_pd idd_pd $&idd_pd vref_re $&vref_re t_re $&t_re",
              "quit", ".endc", ".end"]
    f = os.path.join(HERE, f"tb_m1_{dut}_{test}.spice")
    open(f, "w").write("\n".join(s) + "\n")
    return f

if __name__ == "__main__":
    for d in NETS:
        if os.path.exists(NETS[d]):
            for t in ("op", "ac", "tran"):
                print(tb(d, t))
        else:
            print(f"skip {d}: {NETS[d]} missing")
