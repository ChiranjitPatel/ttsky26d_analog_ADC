#!/usr/bin/env python3
"""B7 (PSRR at vbg_f) over corners on the schematic and the R+C-extracted M1 top level (Phase 3 check).
5 process x 3 temperatures x 3 supplies, both netlists; writes sim/m1/corners_b7.md."""
import itertools, os, re, subprocess
from concurrent.futures import ThreadPoolExecutor
HERE = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(HERE, "..", "out", "m1", "corners")
os.makedirs(OUT, exist_ok=True)
PROC, TEMPS, VDDS = ("tt", "ff", "ss", "fs", "sf"), (-40, 27, 125), (1.62, 1.8, 1.98)
def run(job):
    dut, p, t, v = job
    s = open(os.path.join(HERE, f"tb_m1_{dut}_ac.spice")).read()
    s = s.replace("sky130.lib.spice tt", f"sky130.lib.spice {p}").replace(".temp 27", f".temp {t}")
    s = s.replace("VDD vdd 0 dc 1.8 ac 1", f"VDD vdd 0 dc {v} ac 1")
    s = re.sub(r"wrdata \S+ ", f"wrdata ../out/m1/corners/{dut}_{p}_{t}_{v}.dat ", s)
    f = os.path.join(OUT, f"tb_{dut}_{p}_{t}_{v}.spice"); open(f, "w").write(s)
    r = subprocess.run(["ngspice", "-b", f], capture_output=True, text=True, cwd=HERE)
    m = re.search(r"RES psrr vbg_f_dc (\S+) vbg_f_1m (\S+)", r.stdout)
    return job, (float(m.group(1)), float(m.group(2))) if m else (float("nan"), float("nan"))
jobs = list(itertools.product(("sch", "rc"), PROC, TEMPS, VDDS))
with ThreadPoolExecutor(4) as ex:
    res = dict(ex.map(run, jobs))
md = ["# B7 over corners: schematic vs extracted layout (M1 top, Phase 3)", "",
      "PSRR at `vbg_f`, DC / 1 MHz in dB. Targets: DC ≥ 40 dB at 1.8 V, ≥ 30 dB at 1.62 V; 1 MHz ≥ 20 dB.",
      "Generated by `corners_b7.py`.", "",
      "| corner | T [°C] | VDD [V] | sch DC | layout DC | sch 1 MHz | layout 1 MHz |", "|---|---|---|---|---|---|---|"]
for p, t, v in itertools.product(PROC, TEMPS, VDDS):
    a, b = res[("sch", p, t, v)], res[("rc", p, t, v)]
    flag = " ❌" if b[1] < 20 else ""
    md.append(f"| {p} | {t} | {v} | {a[0]:.1f} | {b[0]:.1f} | {a[1]:.1f} | {b[1]:.1f}{flag} |")
for d in ("sch", "rc"):
    w = min(((res[(d,) + k][1], k) for k in itertools.product(PROC, TEMPS, VDDS)))
    md.append(f"\n**{'schematic' if d == 'sch' else 'layout'}: worst 1 MHz {w[0]:.1f} dB at {w[1]}**")
open(os.path.join(HERE, "corners_b7.md"), "w").write("\n".join(md) + "\n")
print("\n".join(md[-2:]))
fails = [(k, res[("rc",) + k][1]) for k in itertools.product(PROC, TEMPS, VDDS) if res[("rc",) + k][1] < 20]
print("layout 1 MHz < 20 dB:", fails)
