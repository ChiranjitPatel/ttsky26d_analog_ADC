#!/usr/bin/env python3
"""M2 post-layout testbench: full conversions on the whole tile, driven only through its pins (TT demo board).

Two netlists of tt_um_chiranjitpatel_sar_adc:
  sch  layout/cells/m2_top_ref.spice (written by layout/m2_top.py: xschem analog subckts + LibreLane adc_digital)
  rc   sim/out/layout/m2_rc/m2_rc.spice (flat R+C extraction of gds/, `python3 layout/m1_pex.py m2`)
Setup: internal reference (BG_PD = VREF_OE = REF_SEL = 0), INSEL = 0 (ua[0]), MODE = 0, START = 1 from 30.4 us.
clk 1 MHz; rst_n high at 1.5 us. One conversion every 10 us; the first SAMPLE starts at 32 us (the reference
has settled by then, see sim/m1). VIN steps right after each EOC.
Pads (CLAUDE.md rule 2): ua[0] 5 pF on the chip side + 500 Ohm to the ideal source; ua[1] 5 pF + 500 Ohm to a
10 MOhm || 10 pF DMM. Unused pins: inputs to ground, other outputs 1 GOhm to ground.
Usage: python3 make_tb.py [vin ...]   -> tb_m2_sch.spice, tb_m2_rc.spice (rc only if the extraction exists)
"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
TOP = "tt_um_chiranjitpatel_sar_adc"
NETS = {"sch": os.path.join(ROOT, "layout", "cells", "m2_top_ref.spice"),
        "rc": os.path.join(ROOT, "sim", "out", "layout", "m2_rc", "m2_rc.spice")}
VINS = [float(x) for x in sys.argv[1:]] or [0.05, 0.31, 0.6, 0.9, 1.17]
T, TCONV, T0 = 1e-6, 10e-6, 32e-6
PINS = {"VDPWR": "vdd", "VGND": "0", "clk": "clk", "rst_n": "rst_n", "ui_in[0]": "start", "ua[0]": "pad0",
        "ua[1]": "pad1", "uio_out[5]": "eoc", "uio_out[4]": "cmp"}
PINS.update({f"uo_out[{i}]": f"d{i}" for i in range(8)})


def ports(path):
    txt = open(path).read()
    m = re.search(rf"^\.subckt {re.escape(TOP)}\b(.*?)\n(?!\+)", txt, re.M | re.S)
    return m.group(1).replace("\n+", " ").split()


def tb(dut):
    p = ports(NETS[dut])
    conn = []
    for x in p:
        if x in PINS:
            conn.append(PINS[x])
        elif x.startswith(("ui_in", "uio_in", "ena")):
            conn.append("0")
        else:
            conn.append("nc_" + re.sub(r"[^0-9a-z_]", "_", x))
    nc = sorted({c for c in conn if c.startswith("nc_")})
    pwl = []
    for k, v in enumerate(VINS):
        t0 = max(T0 + k * TCONV - 1.5e-6, 0); t1 = T0 + (k + 1) * TCONV - 1.5e-6
        pwl.append(f"{t0:.9g} {v:.9g} {t1 - 1e-9:.9g} {v:.9g}")
    tstop = T0 + len(VINS) * TCONV + 2e-6
    vec = "v(clk) v(eoc) v(vsrc) v(pad0) v(pin1) " + " ".join(f"v(d{i})" for i in range(8))
    s = [f"* M2 post-layout: {len(VINS)} conversions on the {dut} netlist (generated by sim/m2/make_tb.py), tt, 27 C, 1.8 V",
         ".lib /usr/local/share/pdk/sky130A/libs.tech/ngspice/sky130.lib.spice tt",
         ".include /usr/local/share/pdk/sky130A/libs.ref/sky130_fd_sc_hd/spice/sky130_fd_sc_hd.spice" if dut == "rc" else "",
         f".include {NETS[dut]}", ".temp 27",
         # vntol 1e-7 (trapezoidal or gear) fails at the first clock edge: "timestep too small" in the ptat_out
         # xhigh_po divider (the resistor model overflows in rejected Newton steps). 1 uV is still << 1 LSB.
         ".options reltol=1e-5 abstol=1e-12 vntol=1e-6 method=gear",
         f"xdut {' '.join(conn)} {TOP}",
         "VDD vdd 0 1.8",
         "VCLK clk 0 pulse(0 1.8 0.5u 0.5n 0.5n 0.5u 1u)",
         "VRST rst_n 0 pwl(0 0 1.5u 0 1.501u 1.8)",
         f"VST start 0 pwl(0 0 {T0 - 1.6e-6:.6g} 0 {T0 - 1.599e-6:.6g} 1.8)",
         "VIN vsrc 0 pwl(" + " ".join(pwl) + ")", "RPAD0 vsrc pad0 500", "CPAD0 pad0 0 5p",
         "CPAD1 pad1 0 5p", "RPAD1 pad1 pin1 500", "CDMM pin1 0 10p", "RDMM pin1 0 10meg",
         "* unused outputs: 1 GOhm to ground",
         *[f"R{c} {c} 0 1g" for c in nc],
         ".control", "set wr_singlescale", "set wr_vecnames", f"save {vec} i(VDD)",
         f"tran 2n {tstop:.6g}",
         f"wrdata ../out/m2/{dut}.dat {vec}",
         "quit", ".endc", ".end"]
    f = os.path.join(HERE, f"tb_m2_{dut}.spice")
    open(f, "w").write("\n".join(x for x in s if x) + "\n")
    open(os.path.join(ROOT, "sim", "out", "m2", f"{dut}_vin.txt"), "w").write("\n".join(map(str, VINS)) + "\n")
    return f


if __name__ == "__main__":
    os.makedirs(os.path.join(ROOT, "sim", "out", "m2"), exist_ok=True)
    for d in NETS:
        print(tb(d) if os.path.exists(NETS[d]) else f"skip {d}: {NETS[d]} missing")
