#!/usr/bin/env python3
"""I4 operating scenarios (docs/specs/top_level.md) on the whole tile, driven only through its pins.

Same DUT, pad models and simulator settings as make_tb.py (tt, 27 C, 1.8 V). One testbench per scenario:
  gnd       INSEL = 11 (VGND) at 1 MHz, with VREF_OE = 1 and a 10 MOhm DMM on ua[1]   -> code 0, ua[1] = VREF
  vptat     INSEL = 01 (temperature sensor), clk 100 kHz                               -> ~ 256 VPTAT / VREF
  vbg       REF_SEL = 1 (1.500 V + 100 nF on ua[1]), INSEL = 10, clk 100 kHz           -> ~ 256 VBG / 1.5
  fallback  REF_SEL = 1 (1.500 V on ua[1]) with BG_PD = 1 (bandgap off), INSEL = 00    -> 256 vin / 1.5
  mode1     MODE = 1: EXT_SAMPLE high then low, then trial codes on EXT_D with an EXT_CMP_CLK pulse each;
            CMP_OUT must be 0 for trial codes below the input and 1 above it
Usage: python3 scenarios.py [netlist: sch|rc] -> tb_scen_<name>_<netlist>.spice; run with ngspice -b,
then python3 scenarios.py --report  -> scenarios.md
"""
import os, re, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "sim", "out", "m2")
TOP = "tt_um_chiranjitpatel_sar_adc"
NETS = {"sch": os.path.join(ROOT, "layout", "cells", "m2_top_ref.spice"),
        "rc": os.path.join(ROOT, "sim", "out", "layout", "m2_rc", "m2_rc.spice")}
VREF_I3, VEXT = 1.2143, 1.5    # I3 value; the expectations use VREF as measured on ua[1] in the gnd run
TRIALS = [120, 126, 127, 133]            # mode1 trial codes; vin 0.6 V is code 126.5 on the internal reference

# scenario: static pin levels (1 = 1.8 V), clock period, tstop, ua[1] setup, vin
SC = {
    "gnd":      dict(pins={"ui_in[0]": "start", "ui_in[1]": 1, "uio_in[6]": 1, "uio_in[7]": 1}, tclk=1e-6,
                     tstop=15e-6, ua1="dmm", vin=[0.6]),
    "vptat":    dict(pins={"ui_in[0]": "start", "uio_in[6]": 1}, tclk=10e-6, tstop=125e-6, ua1="dmm", vin=[0.6]),
    "vbg":      dict(pins={"ui_in[0]": "start", "uio_in[3]": 1, "uio_in[7]": 1}, tclk=10e-6, tstop=125e-6,
                     ua1="ext", vin=[0.6]),
    "fallback": dict(pins={"ui_in[0]": "start", "ui_in[3]": 1, "uio_in[3]": 1}, tclk=1e-6, tstop=25e-6,
                     ua1="ext", vin=[0.6, 1.17]),
    "mode1":    dict(pins={"uio_in[0]": 1, "uio_in[1]": "ext_sample", "uio_in[2]": "ext_cmp_clk",
                           **{f"ui_in[{i}]": f"ext_d{i}" for i in range(8)}}, tclk=1e-6,
                     tstop=4e-6 + 1e-6 * len(TRIALS) + 0.5e-6, ua1="dmm", vin=[0.6]),
}
T0 = 3e-6                                  # START rises at T0 - 1.6 us (as in make_tb.py)


def ports(path):
    txt = open(path).read()
    m = re.search(rf"^\.subckt {re.escape(TOP)}\b(.*?)\n(?!\+)", txt, re.M | re.S)
    return m.group(1).replace("\n+", " ").split()


def pwl(points):
    return "pwl(" + " ".join(f"{t:.9g} {v:.9g}" for t, v in points) + ")"


def mode1_sources():
    """EXT_SAMPLE high until 3 us, then each trial code from 3.2 + k us with an EXT_CMP_CLK pulse at +0.4..0.6 us."""
    s = [f"VEXS ext_sample 0 {pwl([(0, 1.8), (3e-6, 1.8), (3.001e-6, 0)])}"]
    ck = [(0, 0)]
    bits = {i: [(0, 0)] for i in range(8)}
    for k, code in enumerate(TRIALS):
        t = 3.2e-6 + k * 1e-6
        for i in range(8):
            v = 1.8 if (code >> i) & 1 else 0.0
            bits[i] += [(t - 0.001e-6, bits[i][-1][1]), (t, v)]
        ck += [(t + 0.4e-6, 0), (t + 0.401e-6, 1.8), (t + 0.6e-6, 1.8), (t + 0.601e-6, 0)]
    s.append(f"VEXC ext_cmp_clk 0 {pwl(ck)}")
    s += [f"VEXD{i} ext_d{i} 0 {pwl(bits[i])}" for i in range(8)]
    return s


def tb(name, dut):
    c = SC[name]
    pins = {"VDPWR": "vdd", "VGND": "0", "clk": "clk", "rst_n": "rst_n", "ua[0]": "pad0", "ua[1]": "pad1",
            "uio_out[5]": "eoc", "uio_out[4]": "cmp", **{f"uo_out[{i}]": f"d{i}" for i in range(8)}}
    conn = []
    for x in ports(NETS[dut]):
        if x in c["pins"]:
            v = c["pins"][x]
            conn.append("vdd" if v == 1 else v)
        elif x in pins:
            conn.append(pins[x])
        elif x.startswith(("ui_in", "uio_in", "ena")):
            conn.append("0")
        else:
            conn.append("nc_" + re.sub(r"[^0-9a-z_]", "_", x))
    nc = sorted({x for x in conn if x.startswith("nc_")})
    tc = c["tclk"]
    tconv = 10 * tc
    pw = []
    for k, v in enumerate(c["vin"]):
        t0 = max(T0 + k * tconv - 1.5e-6, 0); t1 = T0 + (k + 1) * tconv - 1.5e-6
        pw += [(t0, v), (t1 - 1e-9, v)]
    vec = "v(clk) v(eoc) v(vsrc) v(pad0) v(pin1) v(cmp) " + " ".join(f"v(d{i})" for i in range(8))
    s = [f"* I4 scenario '{name}' on the {dut} netlist (generated by sim/m2/scenarios.py), tt, 27 C, 1.8 V",
         ".lib /usr/local/share/pdk/sky130A/libs.tech/ngspice/sky130.lib.spice tt",
         ".include /usr/local/share/pdk/sky130A/libs.ref/sky130_fd_sc_hd/spice/sky130_fd_sc_hd.spice" if dut == "rc" else "",
         f".include {NETS[dut]}", ".temp 27",
         ".options reltol=1e-5 abstol=1e-12 vntol=1e-6 method=gear rshunt=1e12",   # see make_tb.py
         f"xdut {' '.join(conn)} {TOP}",
         "VDD vdd 0 1.8",
         f"VCLK clk 0 pulse(0 1.8 {tc / 2:.6g} 0.5n 0.5n {tc / 2:.6g} {tc:.6g})",
         "VRST rst_n 0 pwl(0 0 1.5u 0 1.501u 1.8)",
         f"VST start 0 pwl(0 0 {T0 - 1.6e-6:.6g} 0 {T0 - 1.599e-6:.6g} 1.8)",
         f"VIN vsrc 0 {pwl(pw)}", "RPAD0 vsrc pad0 500", "CPAD0 pad0 0 5p",
         "CPAD1 pad1 0 5p", "RPAD1 pad1 pin1 500"]
    if c["ua1"] == "dmm":
        s += ["CDMM pin1 0 10p", "RDMM pin1 0 10meg"]
    else:                                   # external reference, decoupled next to the pin (docs/info.md test 5)
        s += [f"VEXT ext 0 {VEXT}", "REXT ext pin1 10", "CDEC pin1 0 100n"]
    if name == "mode1":
        s += mode1_sources()
    s += ["* unused outputs: 1 GOhm to ground", *[f"R{x} {x} 0 1g" for x in nc],
          ".control", "set wr_singlescale", "set wr_vecnames", f"save {vec}",
          f"tran {min(tc / 500, 2e-9):.3g} {c['tstop']:.6g}",
          f"wrdata ../out/m2/scen_{name}_{dut}.dat {vec}", "quit", ".endc", ".end"]
    f = os.path.join(HERE, f"tb_scen_{name}_{dut}.spice")
    open(f, "w").write("\n".join(x for x in s if x) + "\n")
    return f


def report():
    rows = ["| Scenario | Settings | Expected | Result | |", "|---|---|---|---|---|"]
    def load(n):
        f = os.path.join(OUT, f"scen_{n}_sch.dat")
        return np.loadtxt(f, skiprows=1) if os.path.exists(f) else None
    def codes(d):
        t, eoc = d[:, 0], d[:, 2]; bits = d[:, 7:15]
        rise = np.where((eoc[:-1] < 0.9) & (eoc[1:] >= 0.9))[0]
        out = []
        for k in rise:
            kk = int(np.argmin(abs(t - (t[k] + 0.2e-6))))
            out.append(int(sum(int(bits[kk, b] > 0.9) << b for b in range(8))))
        return out
    ok = lambda x: "✅" if x else "❌"
    VREF_INT = VREF_I3
    d = load("gnd")
    if d is not None:
        # DMM reading = the DC level before the conversions start (during conversions the DAC's charge draws dip
        # ua[1] by up to ~35 mV for a few hundred ns; a DMM averages them out)
        c = codes(d); v1 = d[int(np.argmin(abs(d[:, 0] - (T0 - 0.2e-6)))), 5]; VREF_INT = v1
        rows.append(f"| VGND input + VREF check | INSEL = 11, VREF_OE = 1, 10 MΩ DMM on ua[1], 1 MHz | code 0; ua[1] ≈ VREF "
                    f"(I3: {VREF_I3} V) | codes {c}; ua[1] = {v1:.4f} V (used as VREF below) | "
                    f"{ok(c and all(x == 0 for x in c) and abs(v1 - VREF_I3) < 0.01)} |")
    d = load("vptat")
    if d is not None:
        c = codes(d)
        e = 256 * 0.599 / VREF_INT
        rows.append(f"| Temperature sensor | INSEL = 01, 100 kHz | ≈ 256 · 0.599 / {VREF_INT:.4f} = {e:.1f} (VPTAT 0.599 V, I3) | "
                    f"codes {c} | {ok(c and abs(c[0] - e) <= 3)} |")
    d = load("vbg")
    if d is not None:
        c = codes(d); e = 256 * 1.2143 / VEXT
        rows.append(f"| Bandgap via ADC | REF_SEL = 1 ({VEXT} V + 100 nF on ua[1]), INSEL = 10, 100 kHz | "
                    f"≈ 256 · VBG / {VEXT} = {e:.1f} | codes {c} | {ok(c and abs(c[0] - e) <= 3)} |")
    d = load("fallback")
    if d is not None:
        c = codes(d); e = [int(256 * v / VEXT) for v in SC["fallback"]["vin"]]
        rows.append(f"| Bandgap fallback | REF_SEL = 1 ({VEXT} V), BG_PD = 1, vin {SC['fallback']['vin']} V, 1 MHz | "
                    f"floor(256 vin / {VEXT}) = {e} | codes {c} | {ok(len(c) >= len(e) and all(abs(a - b) <= 1 for a, b in zip(c, e)))} |")
    d = load("mode1")
    if d is not None:
        t = d[:, 0]; cmpv = d[:, 6]
        r = [int(cmpv[int(np.argmin(abs(t - (3.2e-6 + k * 1e-6 + 0.95e-6))))] > 0.9) for k in range(len(TRIALS))]
        dm = [int(sum(int(d[int(np.argmin(abs(t - (3.2e-6 + k * 1e-6 + 0.3e-6)))), 7 + b] > 0.9) << b for b in range(8)))
              for k in range(len(TRIALS))]
        exp = [int(x > 256 * 0.6 / VREF_INT) for x in TRIALS]       # trial level above vin -> CMP_OUT = 1
        rows.append(f"| External SAR (MODE = 1) | vin 0.6 V, trial codes {TRIALS} on EXT_D | CMP_OUT {exp}; D mirrors EXT_D | "
                    f"CMP_OUT {r}; D {dm} | {ok(r == exp and dm == TRIALS)} |")
    txt = "\n".join(rows)
    print(txt)
    open(os.path.join(HERE, "scenarios.md"), "w").write(
        "# I4 operating scenarios on the whole tile (schematic netlist, tt, 27 °C, 1.8 V)\n\n"
        "Generated by `scenarios.py --report`; settings from `docs/specs/top_level.md`, pins only, pad models as in "
        "`make_tb.py`.\n\n" + txt + "\n")


if __name__ == "__main__":
    if "--report" in sys.argv:
        report(); sys.exit()
    dut = sys.argv[1] if len(sys.argv) > 1 else "sch"
    os.makedirs(OUT, exist_ok=True)
    for n in SC:
        print(tb(n, dut))
