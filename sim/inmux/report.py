#!/usr/bin/env python3
"""Stage 7 report: inmux selection, TG on-resistance, crosstalk, sampling settling (A9) per input."""
import os, re
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

H = os.path.dirname(os.path.abspath(__file__))
O = os.path.join(H, "..", "out", "inmux")
log = open(os.path.join(O, "tb_inmux.log")).read() + open(os.path.join(O, "tb_sample.log")).read()
val = lambda k: float(re.search(rf"^{re.escape(k)}\s*=\s*(\S+)", log, re.M).group(1))
LSB = 1.215 / 256
o = [val(f"v(o{k})") for k in range(4)]
ron = np.loadtxt(os.path.join(O, "ron.dat"), skiprows=1)
ron = ron[abs(ron[:, 0] - 0.6) > 0.1]   # no current flows when vin = 0.6 V (the load return)
xt = np.loadtxt(os.path.join(O, "xtalk.dat"), skiprows=1); xtalk = xt[:, 1].max() - xt[:, 1].min()
sm = np.loadtxt(os.path.join(O, "sample.dat"), skiprows=1); t = sm[:, 0]
vcm = val("vcma_ref")
targets = {"VIN (full-scale step via pad)": (sm[:, 1], 1.2 - vcm),
           "VPTAT (real ptat_out)": (sm[:, 2], val("p_ref") - val("vcmp_ref")),
           "VBG (real bandgap_core)": (sm[:, 3], val("g_ref") - val("vcmg_ref"))}
rows, curves = [], {}
for name, (v, ideal) in targets.items():
    m = t >= 30e-6; err = v[m] - ideal; tt = t[m] - 30e-6
    bad = np.where(abs(err) > 0.5 * LSB)[0]
    ts = tt[bad[-1] + 1] if len(bad) else 0.0
    e1 = err[np.argmin(abs(tt - 1e-6))]; e10 = err[np.argmin(abs(tt - 10e-6))]
    rows.append((name, e1, e10, ts)); curves[name] = (tt, err)

os.makedirs(os.path.join(H, "plots"), exist_ok=True)
fig, ax = plt.subplots(1, 2, figsize=(12, 3.8))
for name, (tt, err) in curves.items():
    ax[0].semilogy(tt * 1e6, np.maximum(abs(err), 1e-7) / LSB, label=name)
ax[0].axhline(0.5, color="k", ls="--", lw=0.8); ax[0].axvline(1, color="C3", ls=":", lw=0.8)
ax[0].set(xlabel="time into sample phase [µs]", ylabel="|error| [LSB]", title="Sampling settling (A9 limit 0.5 LSB)", xlim=(0, 15)); ax[0].legend(fontsize=7)
ax[1].plot(ron[:, 0], ron[:, 1] / 1e3); ax[1].set(xlabel="input [V]", ylabel="R_on [kΩ]", title="Mux TG on-resistance")
for a in ax: a.grid(alpha=0.3, which="both")
fig.tight_layout(); fig.savefig(os.path.join(H, "plots", "inmux.png"), dpi=90)

ok = lambda c: "✅" if c else "❌"
md = ["# Stage 7 — inmux + vcm_gen results", "", "tt, 27 °C, VDPWR 1.80 V. Generated by `report.py` (`./run.sh`).", "",
      "| Spec | Quantity | Result | Target | | Phase |", "|---|---|---|---|---|---|",
      f"| — | Selection 00/01/10/11 (inputs 0.3 / 0.6 / 1.2 V / VGND) | {o[0]:.3f} / {o[1]:.3f} / {o[2]:.3f} / {o[3]*1e3:.3f}m V | follows INSEL | {ok(abs(o[0]-0.3)<1e-3 and abs(o[1]-0.6)<1e-3 and abs(o[2]-1.2)<1e-3 and abs(o[3])<1e-3)} | 1 |",
      f"| — | Mux TG on-resistance, 0 … 1.2 V (excluding ±0.1 V around the 0.6 V test return) | {ron[:,1].min()/1e3:.2f} … {ron[:,1].max()/1e3:.2f} kΩ | — | | 1 |",
      f"| A14 | DC crosstalk: unselected input 0 → 1.2 V, selected behind 500 Ω | {xtalk*1e6:.2f} µV | ≤ 0.25 LSB = {0.25*LSB*1e3:.2f} mV | {ok(xtalk <= 0.25*LSB)} | 1 |",
      f"| — | vcm | {vcm:.4f} V | ≈ 0.6–0.75 V (value cancels) | | 1 |"]
for name, e1, e10, ts in rows:
    need = "1 µs (1 MHz clock)" if name.startswith("VIN") else "10 µs (≤ 100 kHz clock)"
    good = abs(e1) <= 0.5 * LSB if name.startswith("VIN") else abs(e10) <= 0.5 * LSB
    md.append(f"| A9 | Sampling error, {name}: after 1 µs / 10 µs; settles to 0.5 LSB in | {e1*1e3:+.3f} / {e10*1e3:+.4f} mV; {ts*1e6:.2f} µs | ≤ 0.5 LSB within {need} | {ok(good)} | 1 |")
md += ["", "![inmux](plots/inmux.png)", ""]
open(os.path.join(H, "results.md"), "w").write("\n".join(md))
print("\n".join(md))
