#!/usr/bin/env python3
"""M0 — top-level frame for tt_um_chiranjitpatel_sar_adc (Magic, from TT's tt_analog_1x2.def).

Writes layout/m0_frame.tcl and runs Magic on it, producing:
  mag/tt_um_chiranjitpatel_sar_adc.mag, gds/tt_um_chiranjitpatel_sar_adc.gds, lef/tt_um_chiranjitpatel_sar_adc.lef
Contents (following TT's magic_init_project.tcl):
  * outline and all pins from the DEF (def read)
  * power stripes from layout/floorplan.json: vertical met4, 2 um wide, y = 5 ... 217 um (TT rule: start in
    the bottom 10 um, reach the top 10 um; they end below the output-pin tie stubs)
  * every digital output (uo_out, uio_out, uio_oe) tied to VGND: met4 stub from the pin down to a
    met3 bar (via3), and the bar to the VGND stripe (via3). Inputs and ua[] stay unconnected.
Usage: python3 layout/m0_frame.py   (from the repository root)
"""
import os, re, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOP = "tt_um_chiranjitpatel_sar_adc"
DEF = os.path.join(ROOT, "layout", "tt_analog_1x2.def")
PDK = os.environ.get("PDK_ROOT", "/usr/local/share/pdk")
STRIPE_W = 2.0
import json
# stripes from the floorplan (layout/floorplan.json): (net, x of the left edge in um)
_fp = json.load(open(os.path.join(ROOT, "layout", "floorplan.json")))
STRIPES = [(n, x0) for n, x0, x1 in _fp["stripes"]]
STRIPE_Y0, STRIPE_Y1 = _fp["stripe_y"]
TIE_BAR_Y = 219.5                                # met3 tie bar for the unused outputs (um, centre)

# output pin positions from the DEF (centre x in um, top edge)
d = open(DEF).read()
outs = []
for name, x, y in re.findall(r"- (u(?:o_out|io_out|io_oe)\[\d+\]) \+ NET .*?\+ PLACED \( (\d+) (\d+) \) N ;", d, re.S):
    outs.append((name, int(x) / 1000.0, int(y) / 1000.0))
assert len(outs) == 24, f"expected 24 output pins, found {len(outs)}"

L = [f"# generated by layout/m0_frame.py", "drc off", "snap internal",
     f"def read {DEF}", f"cellname rename tt_um_template {TOP}", f"load {TOP}"]
for net, x in STRIPES:
    L += [f"box {x}um {STRIPE_Y0}um {x + STRIPE_W}um {STRIPE_Y1}um", "paint met4",
          f"label {net} FreeSans 0.25u -met4", "port make",
          f"port use {'ground' if net == 'VGND' else 'power'}", "port class bidirectional",
          "port connections n s e w"]
vgnd_x = min(x for n, x in STRIPES if n == "VGND")   # left-most VGND stripe
xs = sorted(x for _, x, _ in outs)
# met3 bar from the VGND stripe to the right-most output
L += [f"box {vgnd_x}um {TIE_BAR_Y - 0.3}um {xs[-1] + 0.3}um {TIE_BAR_Y + 0.3}um", "paint met3",
      f"box {vgnd_x + 0.6}um {TIE_BAR_Y - 0.25}um {vgnd_x + 1.4}um {TIE_BAR_Y + 0.25}um", "paint via3",
      # the stripes end at y = 217; extend the left-most VGND stripe up to the bar (no pins above it)
      f"box {vgnd_x}um {STRIPE_Y1 - 1}um {vgnd_x + STRIPE_W}um {TIE_BAR_Y + 0.5}um", "paint met4"]
for name, x, y in outs:
    # met4 stub from the pin (y = 224.76 ... 225.76) down over the bar, via3 onto the bar
    L += [f"box {x - 0.15}um {TIE_BAR_Y - 0.3}um {x + 0.15}um {y - 0.5}um", "paint met4",
          f"box {x - 0.2}um {TIE_BAR_Y - 0.25}um {x + 0.2}um {TIE_BAR_Y + 0.25}um", "paint via3",
          f"box {x - 0.3}um {TIE_BAR_Y - 0.35}um {x + 0.3}um {TIE_BAR_Y + 0.35}um", "paint met4"]
L += ["select top cell", "drc on", "drc check", "drc catchup",
      'puts "DRC_COUNT [drc list count total]"',
      f"save {ROOT}/mag/{TOP}.mag",
      f"gds write {ROOT}/gds/{TOP}.gds",
      f"lef write {ROOT}/lef/{TOP}.lef -hide -pinonly", "quit -noprompt"]
for d_ in ("mag", "gds", "lef"):
    os.makedirs(os.path.join(ROOT, d_), exist_ok=True)
tcl = os.path.join(ROOT, "layout", "m0_frame.tcl")
open(tcl, "w").write("\n".join(L) + "\n")
rc = os.path.join(PDK, "sky130A", "libs.tech", "magic", "sky130A.magicrc")
r = subprocess.run(["magic", "-dnull", "-noconsole", "-rcfile", rc, tcl], capture_output=True, text=True, cwd=ROOT)
log = r.stdout + r.stderr
open(os.path.join(ROOT, "layout", "m0_frame.log"), "w").write(log)
print([l for l in log.splitlines() if "DRC_COUNT" in l or "rror" in l][:10])
