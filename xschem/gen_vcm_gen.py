#!/usr/bin/env python3
"""Stage 7 — vcm_gen: comparator/top-plate common-mode voltage (~0.6 V) + top-plate sampling switch.

Generates xschem/vcm_gen.sch + .sym.   python3 xschem/gen_vcm_gen.py
MB (pfet_01v8_lvt 2/2 x10 from pbias) pushes 10 uA into MD (nfet_01v8 diode) -> vcm ~ Vgs ~ 0.6 V.
CV (nfet gate cap) decouples vcm. Its exact value cancels: the top plate is sampled to vcm and the
comparator's other input is the same node, so vcm only has to be stable over one conversion.
MTOP (nfet 1/0.15, gate 'smp'): connects the DAC top plate 'vtop' to vcm while sampling. It opens
before the bottom plates switch (bottom-plate sampling), so its charge injection is input-independent.
Ports: VDPWR VGND pbias smp vtop vcm
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))
from xsch import Schematic
NF, PFL = "sky130_fd_pr/nfet_01v8.sym", "sky130_fd_pr/pfet_01v8_lvt.sym"
IUNITS = 10
WD, LD = 4, 1
CVW, CVL, CVM = 8, 8, 4   # ~ 4 x 0.5 pF
s = Schematic()
for p_, d in (("VDPWR", "inout"), ("VGND", "inout"), ("pbias", "in"), ("smp", "in"), ("vtop", "inout"), ("vcm", "out")):
    s.port(p_, d)
s.text("vcm_gen — 0.6 V common mode + top-plate sampling switch (generated by gen_vcm_gen.py)")
s.dev(PFL, "MB", {"D": "vcm", "G": "pbias", "S": "VDPWR", "B": "VDPWR"}, model="pfet_01v8_lvt", spiceprefix="X", W=2, L=2, nf=1, mult=IUNITS)
s.dev(NF, "MD", {"D": "vcm", "G": "vcm", "S": "VGND", "B": "VGND"}, model="nfet_01v8", spiceprefix="X", W=WD, L=LD, nf=1, mult=1)
s.dev(NF, "MCV", {"D": "VGND", "G": "vcm", "S": "VGND", "B": "VGND"}, model="nfet_01v8", spiceprefix="X", W=CVW, L=CVL, nf=1, mult=CVM)
s.dev(NF, "MTOP", {"D": "vtop", "G": "smp", "S": "vcm", "B": "VGND"}, model="nfet_01v8", spiceprefix="X", W=1, L=0.15, nf=1, mult=1)
s.write(os.path.join(os.path.dirname(os.path.abspath(__file__)), "vcm_gen.sch"), sym=True)
print("wrote xschem/vcm_gen.sch, vcm_gen.sym")
