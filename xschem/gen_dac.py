#!/usr/bin/env python3
"""Stage 8 — dac_sw (one bottom-plate switch) and cap_dac (8-bit binary MIM DAC + termination).

Generates xschem/dac_sw.sch/.sym and xschem/cap_dac.sch/.sym.   python3 xschem/gen_dac.py

dac_sw: bottom plate 'bp' of one capacitor group
  smp = 1          -> TG (nfet 1/0.15 + pfet_lvt 2/0.35) connects bp to vadc   (sample)
  smp = 0, b = 1   -> pfet_01v8_lvt 4/0.35 connects bp to vref                 (gate gpb = NAND(smpb, b))
  smp = 0, b = 0   -> nfet_01v8 1/0.15 connects bp to VGND                     (gate gn = NOR(smp, b))
  gn / gpb come from adc_digital (src/sar/sar_drv.v) since 2026-11-16.
  vref sits at 1.215 V, so the vref switch is lvt (a regular pfet has only ~0.2 V overdrive there).
cap_dac: unit cap = cap_mim_m3_1 2 x 1.65 um (~8.0 fF; 2 x 2 = 9.5 fF until 2026-11-16, reduced so the M2 array
  fits: a square 3.5 um pitch with the bottom-plate via2 tab). Groups 128, 64, ... 1 (bits 7..0) plus a
  1-unit termination cap (b tied low) = 256 units ~ 2.38 pF. MIM top plate (c0) = vtop (high
  impedance), bottom plate (c1, met3, more substrate parasitic) = the switched node.
  Switching scheme: see sim/inmux/README.md (sample: top = vcm, bottoms = vadc; then MSB to vref, rest to VGND).
Ports dac_sw:  VDPWR VGND vref vadc smp smpb gn gpb bp
Ports cap_dac: VDPWR VGND vref vadc smp smpb gn0..gn7 gpb0..gpb7 vtop
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))
from xsch import Schematic
HERE = os.path.dirname(os.path.abspath(__file__))
NF, PF, PFL = "sky130_fd_pr/nfet_01v8.sym", "sky130_fd_pr/pfet_01v8.sym", "sky130_fd_pr/pfet_01v8_lvt.sym"
CM = "sky130_fd_pr/cap_mim_m3_1.sym"
CU_W, CU_L = 2.0, 1.65

# ---------------- dac_sw
s = Schematic()
for p_, d in (("VDPWR", "inout"), ("VGND", "inout"), ("vref", "inout"), ("vadc", "inout"),
              ("smp", "in"), ("smpb", "in"), ("gn", "in"), ("gpb", "in"), ("bp", "inout")):
    s.port(p_, d)
s.text("dac_sw — bottom-plate switch: vadc (sample) / vref (gpb=0) / VGND (gn=1)  (generated by gen_dac.py)")
def n(name, d, g, src, W=0.42, L=0.15): s.dev(NF, name, {"D": d, "G": g, "S": src, "B": "VGND"}, model="nfet_01v8", spiceprefix="X", W=W, L=L, nf=1, mult=1)
def p(name, d, g, src, W=0.84, L=0.15, sym=PF, model="pfet_01v8"): s.dev(sym, name, {"D": d, "G": g, "S": src, "B": "VDPWR"}, model=model, spiceprefix="X", W=W, L=L, nf=1, mult=1)
# gn = NOR(smp, b) and gpb = NAND(smpb, b) come from adc_digital (src/sar/sar_drv.v); until 2026-11-16 these
# two gates were transistors in this cell (moved to the standard-cell block for M2 layout area)
n("MSG", "bp", "gn", "VGND", W=1)
p("MSR", "bp", "gpb", "vref", W=4, L=0.35, sym=PFL, model="pfet_01v8_lvt")   # lvt pfet: L >= 0.35 (no model bin below)
n("MSN", "bp", "smp", "vadc", W=1)
p("MSP", "bp", "smpb", "vadc", W=2, L=0.35, sym=PFL, model="pfet_01v8_lvt")
s.write(os.path.join(HERE, "dac_sw.sch"), sym=True)

# ---------------- cap_dac
s = Schematic(cols=6)
ports = [("VDPWR", "inout"), ("VGND", "inout"), ("vref", "inout"), ("vadc", "inout"), ("smp", "in"), ("smpb", "in")]
ports += [(f"gn{i}", "in") for i in range(8)] + [(f"gpb{i}", "in") for i in range(8)] + [("vtop", "inout")]
for p_, d in ports:
    s.port(p_, d)
s.text("cap_dac — 8-bit binary MIM DAC (128..1 + 1 termination = 256 x 9.3 fF)  (generated by gen_dac.py)")
# termination switch: b tied low -> gn = NOR(smp, 0) = smpb, gpb = NAND(smpb, 0) = 1
groups = [(f"gn{i}", f"gpb{i}", 2 ** i, f"bp{i}") for i in range(7, -1, -1)] + [("smpb", "VDPWR", 1, "bpt")]
for gn, gpb, mf, bp in groups:
    s.dev("dac_sw.sym", f"xsw_{bp}", {"VDPWR": "VDPWR", "VGND": "VGND", "vref": "vref", "vadc": "vadc",
                                      "smp": "smp", "smpb": "smpb", "gn": gn, "gpb": gpb, "bp": bp})
    s.dev(CM, f"C_{bp}", {"c0": "vtop", "c1": bp}, W=CU_W, L=CU_L, MF=mf, model="cap_mim_m3_1", spiceprefix="X")
s.write(os.path.join(HERE, "cap_dac.sch"), sym=True)

# ---------------- cap_array (layout chunk 2a: the MIM array alone, for LVS of layout/gen_cap_dac.py)
s = Schematic(cols=6)
for p_, d in [("vtop", "inout")] + [(f"b{i}", "inout") for i in range(7, -1, -1)] + [("bpt", "inout"), ("VGND", "inout")]:
    s.port(p_, d)
s.text("cap_array — 16 x 16 common-centroid MIM units + 32 dummies (generated by gen_dac.py)")
for i in range(7, -1, -1):
    s.dev(CM, f"C{i}", {"c0": "vtop", "c1": f"b{i}"}, W=CU_W, L=CU_L, MF=2 ** i, model="cap_mim_m3_1", spiceprefix="X")
s.dev(CM, "CT", {"c0": "vtop", "c1": "bpt"}, W=CU_W, L=CU_L, MF=1, model="cap_mim_m3_1", spiceprefix="X")
s.dev(CM, "CD", {"c0": "VGND", "c1": "VGND"}, W=CU_W, L=CU_L, MF=32, model="cap_mim_m3_1", spiceprefix="X")   # 2 dummy columns x 16
s.write(os.path.join(HERE, "cap_array.sch"), sym=True)

# ---------------- dac_sw_row (layout chunk 2b: the nine switches in one row, for LVS of layout/gen_dac_sw.py)
s = Schematic(cols=5)
for p_, d in ([("VDPWR", "inout"), ("VGND", "inout"), ("vref", "inout"), ("vadc", "inout"), ("smp", "in"), ("smpb", "in")]
              + [(f"gn{i}", "in") for i in range(8)] + [(f"gpb{i}", "in") for i in range(8)]
              + [(f"bp{i}", "inout") for i in range(8)] + [("bpt", "inout")]):
    s.port(p_, d)
s.text("dac_sw_row — 9 bottom-plate switches (generated by gen_dac.py)")
for gn, gpb, mf, bp in groups:
    s.dev("dac_sw.sym", f"xsw_{bp}", {"VDPWR": "VDPWR", "VGND": "VGND", "vref": "vref", "vadc": "vadc",
                                      "smp": "smp", "smpb": "smpb", "gn": gn, "gpb": gpb, "bp": bp})
s.write(os.path.join(HERE, "dac_sw_row.sch"), sym=True)
print("wrote xschem/dac_sw.sch/.sym, cap_dac.sch/.sym, cap_array.sch/.sym, dac_sw_row.sch/.sym")
