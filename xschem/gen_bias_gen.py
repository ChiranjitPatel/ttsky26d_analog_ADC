#!/usr/bin/env python3
"""Stage 1 — bias_gen: beta-multiplier current reference, 1 uA, with startup and power-down.

Generates xschem/bias_gen.sch + bias_gen.sym. Re-run after editing sizes here:
    python3 xschem/gen_bias_gen.py

Topology (all L = 2 um unless noted):
  MP1, MP2   pfet_01v8_lvt W=2 L=2           PMOS mirror; MP2 diode-connected -> pbias
  MN1        nfet_01v8     W=2 L=2           diode-connected -> nbias
  MN2        nfet_01v8     W=2 L=2 mult=4    K = 4, source degenerated by R1
  R1         res_xhigh_po_0p35               sets I = dVgs / R1
  Startup:   MS2A-E (weak long PMOS pull-up on su, 5 x W=0.42 L=10 in series -> ~0.2 uA) vs. MS3 (copy of the bias current pulling su low);
             MS1 pulls pbias low while su is high, i.e. only when no current flows.
  Power-down (pd = 1): MPD1 pulls pbias to VDPWR, MND1 pulls nbias to VGND, MND2 holds su low,
             MPD2 cuts the startup pull-up current. pdb comes from a local inverter.
Outputs: nbias (gate bias for nfet_01v8 W=2 L=2 sinks, 1 uA each)
         pbias (gate bias for pfet_01v8_lvt W=2 L=2 sources, 1 uA each)
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))
from xsch import Schematic

NF, PF, PFL = "sky130_fd_pr/nfet_01v8.sym", "sky130_fd_pr/pfet_01v8.sym", "sky130_fd_pr/pfet_01v8_lvt.sym"
RX = "sky130_fd_pr/res_xhigh_po_0p35.sym"
R1_L = 11      # um, tuned in stage 1 for 1 uA (see sim/bias/README.md)

s = Schematic()
for p, d in (("VDPWR", "inout"), ("VGND", "inout"), ("pd", "in"), ("nbias", "out"), ("pbias", "out")):
    s.port(p, d)
s.text("bias_gen — beta-multiplier 1 uA bias with startup and power-down (generated by gen_bias_gen.py)")

def n(name, d, g, src, **k): s.dev(NF, name, {"D": d, "G": g, "S": src, "B": "VGND"}, model="nfet_01v8", spiceprefix="X", **k)
def p(name, d, g, src, sym=PFL, model="pfet_01v8_lvt", **k): s.dev(sym, name, {"D": d, "G": g, "S": src, "B": "VDPWR"}, model=model, spiceprefix="X", **k)

# core
p("MP1", "nbias", "pbias", "VDPWR", W=2, L=2, nf=1, mult=1)
p("MP2", "pbias", "pbias", "VDPWR", W=2, L=2, nf=1, mult=1)
n("MN1", "nbias", "nbias", "VGND", W=2, L=2, nf=1, mult=1)
n("MN2", "pbias", "nbias", "nr", W=2, L=2, nf=1, mult=4)
s.dev(RX, "R1", {"P": "nr", "M": "VGND", "B": "VGND"}, W=0.35, L=R1_L, model="res_xhigh_po_0p35", spiceprefix="X", mult=1)
# layout dummies (all terminals on the rail): ends of the MN1/MN2 row and of the MP1/MP2 row.
# netgen does not drop shorted devices, so they are part of the schematic.
for nm in ("MDN1", "MDN2"):
    n(nm, "VGND", "VGND", "VGND", W=2, L=2, nf=1, mult=1)
for nm in ("MDP1", "MDP2"):
    p(nm, "VDPWR", "VDPWR", "VDPWR", W=2, L=2, nf=1, mult=1)
# startup
# MS2: a 0.42/50 PMOS drawn as 5 series devices of L = 10 um (a 50 um gate doesn't fit the 22 x 26 um
# outline); same function: weak pull-up, ~0.2 uA. Stack: sup -> ms2_1 -> ... -> ms2_4 -> su
_ms = ["sup", "ms2_1", "ms2_2", "ms2_3", "ms2_4", "su"]
for i in range(5):
    p(f"MS2{'ABCDE'[i]}", _ms[i + 1], "VGND", _ms[i], sym=PF, model="pfet_01v8", W=0.42, L=10, nf=1, mult=1)
n("MS3", "su", "nbias", "VGND", W=2, L=2, nf=1, mult=1)
n("MS1", "pbias", "su", "VGND", W=0.42, L=1, nf=1, mult=1)
# power-down. Static switches, so not minimum length: at L = 0.15 the off-state leakage at 125 C
# (fast corners) reached 1.5 uA in power-down (MIP) - Phase 2 sweep, 2026-11-08.
p("MPD2", "sup", "pd", "VDPWR", sym=PF, model="pfet_01v8", W=0.42, L=0.5, nf=1, mult=1)
p("MPD1", "pbias", "pdb", "VDPWR", sym=PF, model="pfet_01v8", W=0.42, L=0.5, nf=1, mult=1)
n("MND1", "nbias", "pd", "VGND", W=0.42, L=0.5, nf=1, mult=1)
n("MND2", "su", "pd", "VGND", W=0.42, L=0.5, nf=1, mult=1)
# pd inverter
p("MIP", "pdb", "pd", "VDPWR", sym=PF, model="pfet_01v8", W=0.84, L=1, nf=1, mult=1)
n("MIN", "pdb", "pd", "VGND", W=0.42, L=1, nf=1, mult=1)

s.write(os.path.join(os.path.dirname(os.path.abspath(__file__)), "bias_gen.sch"), sym=True)
print("wrote xschem/bias_gen.sch, bias_gen.sym")
