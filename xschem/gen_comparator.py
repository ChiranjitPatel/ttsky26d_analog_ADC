#!/usr/bin/env python3
"""Stage 6 — comparator: PMOS-input StrongARM latch + inverters + NAND SR latch.

Generates xschem/comparator.sch + .sym.   python3 xschem/gen_comparator.py

Input range: the DAC top plate moves in ~0 ... 1.2 V around vcm ~ 0.6 V (see sim/comparator/README.md),
so the input pair is PMOS (lvt), which works down to 0 V.
  clk = 0 (reset):    tail off; xp/xn (input-pair drains) and op/on (latch outputs) pulled to VGND.
  clk = 1 (evaluate): tail on; the side whose input is LOWER conducts more, its node rises first and
                      the cross-coupled pair regenerates: one of op/on goes to VDPWR.
  The side with the higher input loses, so 'op' (on the inn-pair side) goes high when inp > inn.
  op/on drive identical inverters (opb/onb), then a NAND SR latch: q = 1 when inp > inn; holds
  while opb = onb = 1 (reset). The inverters keep the latch load on op/on equal and independent of
  the stored state (a NOR latch directly on op/on gave state-dependent decisions at 1 mV).
Devices:
  MT        pfet_01v8 4/0.15      tail switch, gate = clkb
  M1/M2     pfet_01v8_lvt 4/0.5   input pair (M1 = inp -> xn side, M2 = inn -> xp side)
  M3/M4     pfet_01v8 1/0.15      cross-coupled PMOS (sources on xp/xn)
  M5/M6     nfet_01v8 1/0.15      cross-coupled NMOS
  MR1..MR4  nfet_01v8 0.42/0.15   reset switches (gate = clkb)
Ports: VDPWR VGND pbias clk inp inn q qb
Preamp (added in I2, see sim/comparator/README.md): MAT/MA1/MA2/MAL1/MAL2 between the inputs and the latch.
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))
from xsch import Schematic

NF, PF, PFL = "sky130_fd_pr/nfet_01v8.sym", "sky130_fd_pr/pfet_01v8.sym", "sky130_fd_pr/pfet_01v8_lvt.sym"
WI, LI = 4, 0.5
PRE_TAIL = 4          # preamp tail, units of 1 uA (pbias)
WPA, LPA = 4, 0.5     # preamp input pair (pfet_01v8_lvt)
WLA, LLA = 0.5, 1     # preamp diode loads (nfet_01v8)

s = Schematic()
for p_, d in (("VDPWR", "inout"), ("VGND", "inout"), ("pbias", "in"), ("clk", "in"), ("inp", "in"), ("inn", "in"), ("q", "out"), ("qb", "out")):
    s.port(p_, d)
s.text("comparator — PMOS-input StrongARM + NOR SR latch (generated by gen_comparator.py)")
def n(name, d, g, src, W=0.42, L=0.15, **k): s.dev(NF, name, {"D": d, "G": g, "S": src, "B": "VGND"}, model="nfet_01v8", spiceprefix="X", W=W, L=L, nf=1, mult=1, **k)
def p(name, d, g, src, W=0.84, L=0.15, sym=PF, model="pfet_01v8", mult=1, **k): s.dev(sym, name, {"D": d, "G": g, "S": src, "B": "VDPWR"}, model=model, spiceprefix="X", W=W, L=L, nf=1, mult=mult, **k)

# clock inverter
p("MCP", "clkb", "clk", "VDPWR", W=1.68); n("MCN", "clkb", "clk", "VGND", W=0.84)
# Preamp (continuous time, added in integration I2): isolates the DAC top plate from the latch's
# clocked kickback. PMOS-lvt pair, 4 uA tail from pbias, diode-connected NMOS loads (gain ~2).
# The latch kicks both preamp outputs equally (same impedance) -> common mode, which cancels.
# inp -> MA1 -> pan (falls when inp rises), inn -> MA2 -> pap; latch input = (pap, pan).
p("MAT", "pts", "pbias", "VDPWR", W=2, L=2, sym=PFL, model="pfet_01v8_lvt", mult=PRE_TAIL)
p("MA1", "pan", "inp", "pts", W=WPA, L=LPA, sym=PFL, model="pfet_01v8_lvt")
p("MA2", "pap", "inn", "pts", W=WPA, L=LPA, sym=PFL, model="pfet_01v8_lvt")
n("MAL1", "pan", "pan", "VGND", W=WLA, L=LLA)
n("MAL2", "pap", "pap", "VGND", W=WLA, L=LLA)
# StrongARM: its 'inp' gate gets pap, 'inn' gate gets pan (inp up -> pan down, pap up -> latch sees +)
p("MT", "ts", "clkb", "VDPWR", W=4, L=0.15)
p("M1", "xn", "pap", "ts", W=WI, L=LI, sym=PFL, model="pfet_01v8_lvt")
p("M2", "xp", "pan", "ts", W=WI, L=LI, sym=PFL, model="pfet_01v8_lvt")
p("M3", "op", "on", "xp", W=1, L=0.15)
p("M4", "on", "op", "xn", W=1, L=0.15)
n("M5", "op", "on", "VGND", W=1, L=0.15)
n("M6", "on", "op", "VGND", W=1, L=0.15)
n("MR1", "xp", "clkb", "VGND"); n("MR2", "xn", "clkb", "VGND")
n("MR3", "op", "clkb", "VGND"); n("MR4", "on", "clkb", "VGND")
# identical inverters on op/on: equal, state-independent load on the latch outputs
p("MIOP", "opb", "op", "VDPWR"); n("MION", "opb", "op", "VGND")
p("MINP", "onb", "on", "VDPWR"); n("MINN", "onb", "on", "VGND")
# NAND SR latch (active-low set/reset): q = NAND(opb, qb), qb = NAND(onb, q); holds while opb = onb = 1
def nand2(tag, a, b, out):
    p(f"MP{tag}A", out, a, "VDPWR"); p(f"MP{tag}B", out, b, "VDPWR")
    n(f"MN{tag}A", out, a, f"m{tag}", W=0.84); n(f"MN{tag}B", f"m{tag}", b, "VGND", W=0.84)
nand2("Q", "opb", "qb", "q")
nand2("QB", "onb", "q", "qb")

s.write(os.path.join(os.path.dirname(os.path.abspath(__file__)), "comparator.sch"), sym=True)
print("wrote xschem/comparator.sch, comparator.sym")
