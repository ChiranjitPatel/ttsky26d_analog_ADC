#!/usr/bin/env python3
"""Stage 7 — inmux: 4:1 ADC input multiplexer (transmission gates) with INSEL decoder.

Generates xschem/inmux.sch + .sym.   python3 xschem/gen_inmux.py
INSEL[1:0]: 00 -> vin (ua[0]), 01 -> vptat, 10 -> vbg, 11 -> VGND (offset check).
Decoder: static NOR2 gates on insel/insel_b give one-hot en0..en3 (+ inverted for the PMOS gates).
TGs: nfet_01v8 W/0.15 + pfet_01v8_lvt W/0.35 (inputs 0 ... 1.2 V; lvt PMOS keeps R_on low near 1 V).
Output 'vadc' goes to the DAC bottom-plate input bus.
Ports: VDPWR VGND insel0 insel1 vin vptat vbg vadc
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))
from xsch import Schematic
NF, PF, PFL = "sky130_fd_pr/nfet_01v8.sym", "sky130_fd_pr/pfet_01v8.sym", "sky130_fd_pr/pfet_01v8_lvt.sym"
TGN_W, TGP_W = 4, 8
s = Schematic()
for p_, d in (("VDPWR", "inout"), ("VGND", "inout"), ("insel0", "in"), ("insel1", "in"),
              ("vin", "in"), ("vptat", "in"), ("vbg", "in"), ("vadc", "out")):
    s.port(p_, d)
s.text("inmux — 4:1 TG mux + INSEL decoder (generated by gen_inmux.py)")
def n(name, d, g, src, W=0.42, L=0.15): s.dev(NF, name, {"D": d, "G": g, "S": src, "B": "VGND"}, model="nfet_01v8", spiceprefix="X", W=W, L=L, nf=1, mult=1)
def p(name, d, g, src, W=0.84, L=0.15, sym=PF, model="pfet_01v8"): s.dev(sym, name, {"D": d, "G": g, "S": src, "B": "VDPWR"}, model=model, spiceprefix="X", W=W, L=L, nf=1, mult=1)
def inv(tag, a, y): p(f"MP{tag}", y, a, "VDPWR"); n(f"MN{tag}", y, a, "VGND")
def nor2(tag, a, b, y):
    p(f"MP{tag}A", f"m{tag}", a, "VDPWR", W=1.68); p(f"MP{tag}B", y, b, f"m{tag}", W=1.68)
    n(f"MN{tag}A", y, a, "VGND"); n(f"MN{tag}B", y, b, "VGND")
inv("I0", "insel0", "s0b"); inv("I1", "insel1", "s1b")
nor2("D0", "insel1", "insel0", "en0")      # 00
nor2("D1", "insel1", "s0b", "en1")         # 01
nor2("D2", "s1b", "insel0", "en2")         # 10
nor2("D3", "s1b", "s0b", "en3")            # 11
for k in range(4):
    inv(f"E{k}", f"en{k}", f"en{k}b")
for k, src in enumerate(("vin", "vptat", "vbg", "VGND")):
    n(f"MTN{k}", "vadc", f"en{k}", src, W=TGN_W)
    p(f"MTP{k}", "vadc", f"en{k}b", src, W=TGP_W, L=0.35, sym=PFL, model="pfet_01v8_lvt")
s.write(os.path.join(os.path.dirname(os.path.abspath(__file__)), "inmux.sch"), sym=True)
print("wrote xschem/inmux.sch, inmux.sym")
