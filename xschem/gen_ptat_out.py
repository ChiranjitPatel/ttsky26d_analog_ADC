#!/usr/bin/env python3
"""Stage 4 — ptat_out: PTAT voltage for the on-chip temperature sensor.

Generates xschem/ptat_out.sch + ptat_out.sym. Re-run after editing sizes here:
    python3 xschem/gen_ptat_out.py

MPP (pfet_01v8 8/4, gate on the bandgap's vgp) copies the core branch current I = dVbe/R1 into
R3 = N3 units of the same res_xhigh_po 0.35/2 used for R1, so
    VPTAT = I * R3 = dVbe * (N3/N1)  -> resistor TC cancels, VPTAT is proportional to T.
N3 = 22 with N1 = 2 -> gain 11.0 on dVbe (54.4 mV at 27 C) -> VPTAT ~ 0.60 V, ~2.0 mV/C.
The branch has its own resistor and never touches the core nodes (only the vgp gate),
so loading vptat (e.g. by the ADC input mux) can't disturb VBG.
Power-down: when the bandgap is off, vgp = VDPWR -> MPP off -> vptat = 0 V through R3.
Ports: VDPWR VGND vgp(in) vptat(out)
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))
from xsch import Schematic

PF, RX = "sky130_fd_pr/pfet_01v8.sym", "sky130_fd_pr/res_xhigh_po_0p35.sym"
LU = 2.0   # um, same unit as bandgap_core R1/R2
N3 = 22

s = Schematic()
for p, d in (("VDPWR", "inout"), ("VGND", "inout"), ("vgp", "in"), ("vptat", "out")):
    s.port(p, d)
s.text("ptat_out — VPTAT = dVbe * N3/N1 (generated by gen_ptat_out.py)")
s.dev(PF, "MPP", {"D": "vptat", "G": "vgp", "S": "VDPWR", "B": "VDPWR"}, model="pfet_01v8", spiceprefix="X", W=8, L=4, nf=1, mult=1)
nodes = ["vptat"] + [f"r3_{i}" for i in range(1, N3)] + ["VGND"]
for i in range(N3):
    s.dev(RX, f"R3_{i+1}", {"P": nodes[i], "M": nodes[i + 1], "B": "VGND"}, W=0.35, L=LU, model="res_xhigh_po_0p35", spiceprefix="X", mult=1)
s.write(os.path.join(os.path.dirname(os.path.abspath(__file__)), "ptat_out.sch"), sym=True)
print("wrote xschem/ptat_out.sch, ptat_out.sym")
