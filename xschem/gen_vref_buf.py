#!/usr/bin/env python3
"""Stage 5 — vref_buf: unity-gain VREF buffer with on-chip reservoir cap, driving the DAC reference.

Generates xschem/vref_buf.sch + .sym.   python3 xschem/gen_vref_buf.py
Single-stage OTA follower, compensated by its load (the reservoir cap CRES):
  MT   nfet_01v8 2/2 x10 (gate nbias) -> 10 uA tail; MSW series switch (gate en) for power-down
  M1/M2 nfet_01v8 W/L = 4/1           input pair (M1 = in, M2 = vref feedback)
  M3/M4 pfet_01v8_lvt 4/1             mirror load; lvt Vsg ~ 0.6 V puts the diode node near 1.2 V,
                                      close to vref -> small systematic offset
  CRES nfet_01v8 gate cap on vref      ~ 6 pF reservoir; also the dominant (only) pole
  MPU  pfet (gate en): pulls the mirror gate to VDPWR when off, so the output goes high-Z
Why single stage: every DAC bit switch pulls charge from VREF; a Miller two-stage OTA can't stay
stable with a large load cap at useful speed, a load-compensated single stage can.
Ports: VDPWR VGND nbias en in vref
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))
from xsch import Schematic
NF, PF, PFL = "sky130_fd_pr/nfet_01v8.sym", "sky130_fd_pr/pfet_01v8.sym", "sky130_fd_pr/pfet_01v8_lvt.sym"
TAIL = 10        # uA (units of the bias_gen nfet 2/2 sink)
WI, LI = 4, 1    # input pair
WL, LL = 4, 1    # lvt mirror load
CRW, CRL, CRM = 10, 10, 7   # reservoir MOS cap: 7 x (10 x 10 um) ~ 6 pF
s = Schematic()
for p, d in (("VDPWR", "inout"), ("VGND", "inout"), ("nbias", "in"), ("en", "in"), ("in", "in"), ("vref", "out")):
    s.port(p, d)
s.text("vref_buf — single-stage follower + reservoir cap (generated by gen_vref_buf.py)")
def n(name, d, g, src, **k): s.dev(NF, name, {"D": d, "G": g, "S": src, "B": "VGND"}, model="nfet_01v8", spiceprefix="X", nf=1, **k)
def p(name, d, g, src, sym=PFL, model="pfet_01v8_lvt", **k): s.dev(sym, name, {"D": d, "G": g, "S": src, "B": "VDPWR"}, model=model, spiceprefix="X", nf=1, **k)
n("MT", "tail_sw", "nbias", "VGND", W=2, L=2, mult=TAIL)
n("MSW", "tail", "en", "tail_sw", W=4, L=0.15, mult=1)
n("M1", "dm", "in", "tail", W=WI, L=LI, mult=1)
n("M2", "vref", "vref", "tail", W=WI, L=LI, mult=1)
p("M3", "dm", "dm", "VDPWR", W=WL, L=LL, mult=1)
p("M4", "vref", "dm", "VDPWR", W=WL, L=LL, mult=1)
p("MPU", "dm", "en", "VDPWR", sym=PF, model="pfet_01v8", W=0.42, L=0.15, mult=1)
s.dev(NF, "MCRES", {"D": "VGND", "G": "vref", "S": "VGND", "B": "VGND"}, model="nfet_01v8", spiceprefix="X", W=CRW, L=CRL, nf=1, mult=CRM)
s.write(os.path.join(os.path.dirname(os.path.abspath(__file__)), "vref_buf.sch"), sym=True)
print("wrote xschem/vref_buf.sch, vref_buf.sym")
