#!/usr/bin/env python3
"""Stage 2 — ota: two-stage Miller OTA, PMOS input, for the bandgap error amplifier.

Generates xschem/ota.sch + ota.sym. Re-run after editing sizes here:
    python3 xschem/gen_ota.py

Why this topology (see sim/ota/README.md):
  * Inputs sit at Vbe ~ 0.55-0.80 V  -> PMOS (lvt) input pair; an NMOS pair would leave no tail headroom.
  * >= 50 dB gain needed             -> two stages (a 5T OTA gives only ~38 dB with these devices).
  * Output ~ 0.7 V drives the gates of the bandgap's pfet_01v8 current sources.

Devices (bias from bias_gen: pbias -> 1 uA per pfet_01v8_lvt W=2 L=2 unit):
  M5        pfet_01v8_lvt 2/2 x2      tail, 2 uA
  M1, M2    pfet_01v8_lvt 32/8        input pair (M1 gate = inn, M2 gate = inp); was 8/2
  (Phase 2 Monte Carlo 2026-11-08: the OTA offset x (1 + R2/R1) dominated sigma(VBG), 49 mV -> 6 mV)
  M3, M4    nfet_01v8     4/16        mirror load (M3 diode on the M1 side); was 1/4
  M6        nfet_01v8     4/16 x4     2nd stage; 4x M3 density at 4 uA -> zero systematic offset
  M7        pfet_01v8_lvt 2/2 x4      2nd-stage load, 4 uA
  CC, RZ    MIM + xhigh_po            Miller compensation with zero-nulling resistor
  Power-down (pd = 1): MPD pulls out to VDPWR (turns the bandgap PMOS sources off), MND pulls
  out1 to VGND (M6 off). pdb from a local inverter. Currents stop when bias_gen is powered down.
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))
from xsch import Schematic

NF, PF, PFL = "sky130_fd_pr/nfet_01v8.sym", "sky130_fd_pr/pfet_01v8.sym", "sky130_fd_pr/pfet_01v8_lvt.sym"
RX, CM = "sky130_fd_pr/res_xhigh_po_0p35.sym", "sky130_fd_pr/cap_mim_m3_1.sym"

CC_W = CC_L = 16.0   # um, CC_MF = 4 in parallel -> ~2.1 pF (one 32 x 32 until 2026-11-12: four 16 x 16 fit over
CC_MF = 4            # the input-pair rows of the layout). Was 18.7 = 0.7 pF before the matching resize. Raised 2026-11-08 after the matching resize (input pair
                     # 32/8, loads 4/16, sources 16/8): PM 9.5 -> 76.4 deg. MIM can sit over the OTA devices.
RZ_L = 10.45         # um per strip, 2 strips in series -> ~120 kOhm (one 21 um strip until 2026-11-12; the layout
                     # row height). Was 7 = 40 kOhm before the larger CC.

s = Schematic()
for p, d in (("VDPWR", "inout"), ("VGND", "inout"), ("pbias", "in"), ("pd", "in"),
             ("inp", "in"), ("inn", "in"), ("out", "out")):
    s.port(p, d)
s.text("ota — two-stage Miller OTA, PMOS input (generated by gen_ota.py)")

def n(name, d, g, src, **k): s.dev(NF, name, {"D": d, "G": g, "S": src, "B": "VGND"}, model="nfet_01v8", spiceprefix="X", nf=1, **k)
def p(name, d, g, src, sym=PFL, model="pfet_01v8_lvt", body="VDPWR", **k):
    s.dev(sym, name, {"D": d, "G": g, "S": src, "B": body}, model=model, spiceprefix="X", nf=1, **k)

# first stage
p("M5", "tail", "pbias", "VDPWR", W=2, L=2, mult=2)
p("M1", "d1", "inn", "tail", W=32, L=8, mult=1)
p("M2", "out1", "inp", "tail", W=32, L=8, mult=1)
n("M3", "d1", "d1", "VGND", W=4, L=16, mult=1)
n("M4", "out1", "d1", "VGND", W=4, L=16, mult=1)
# second stage
n("M6", "out", "out1", "VGND", W=4, L=16, mult=4)
p("M7", "out", "pbias", "VDPWR", W=2, L=2, mult=4)
# compensation: out1 -- RZ -- cz -- CC -- out (MIM bottom plate c1 on the low-impedance output)
s.dev(RX, "RZA", {"P": "out1", "M": "rzm", "B": "VGND"}, W=0.35, L=RZ_L, model="res_xhigh_po_0p35", spiceprefix="X", mult=1)
s.dev(RX, "RZB", {"P": "rzm", "M": "cz", "B": "VGND"}, W=0.35, L=RZ_L, model="res_xhigh_po_0p35", spiceprefix="X", mult=1)
for nm in ("RZD1", "RZD2"):   # layout dummies of the RZ array
    s.dev(RX, nm, {"P": "VGND", "M": "VGND", "B": "VGND"}, W=0.35, L=RZ_L, model="res_xhigh_po_0p35", spiceprefix="X", mult=1)
s.dev(CM, "CC", {"c0": "cz", "c1": "out"}, W=CC_W, L=CC_L, MF=CC_MF, model="cap_mim_m3_1", spiceprefix="X")
# layout dummies (all terminals on the rail): ends of the input-pair row (D A B B A D, 16/8 fingers)
# and of the load row (D M6 M6 M3 M4 M6 M6 D); see docs/specs/layout_briefs/ota.md
for nm in ("MDP1", "MDP2"):   # ends of the input-pair row (D A B B A D);
    p(nm, "VDPWR", "VDPWR", "VDPWR", W=16, L=1, mult=1)   # same W, short L (only the edge environment matters)
# (no load-row dummies: the four M6 units flank M3/M4 in the layout row M6 M6 M3 M4 M6 M6)
# power-down
p("MPD", "out", "pdb", "VDPWR", sym=PF, model="pfet_01v8", W=0.42, L=1, mult=1)   # not min. length: hot leakage (bias_gen Phase 2)
n("MND", "out1", "pd", "VGND", W=0.42, L=1, mult=1)
p("MIP", "pdb", "pd", "VDPWR", sym=PF, model="pfet_01v8", W=0.84, L=1, mult=1)
n("MIN", "pdb", "pd", "VGND", W=0.42, L=1, mult=1)

s.write(os.path.join(os.path.dirname(os.path.abspath(__file__)), "ota.sch"), sym=True)
print("wrote xschem/ota.sch, ota.sym")
