#!/usr/bin/env python3
"""I4 — tt_um_chiranjitpatel_sar_adc: top-level schematic (all proven blocks + adc_digital).

Generates xschem/adc_digital.sym (symbol only; circuit = src/sar/adc_digital.v -> Yosys -> gl2spice)
and xschem/tt_um_chiranjitpatel_sar_adc.sch/.sym.   python3 xschem/gen_top.py
Blocks: bias_gen, bandgap_core, ptat_out, vref_filt, vref_buf, vref_sel, inmux, vcm_gen, cap_dac,
comparator, adc_digital, smpb inverter.
  bias_gen.pd = VGND: the bias stays on (vcm_gen needs it even with BG_PD = 1 / external reference).
  bandgap_core.pd = bg_pd; vref_buf.en = en_buf from vref_sel (off for REF_SEL = 1 or BG_PD = 1).
Ports (TT template, src/project.v): VGND VDPWR ui_in[7:0] uo_out[7:0] uio_in[7:0] uio_out[7:0]
uio_oe[7:0] ua[7:0] ena clk rst_n. ua[0] = VIN, ua[1] = VREF out / external VREF in, ua[2..7] unconnected here (VGND in layout).
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))
from xsch import Schematic
HERE = os.path.dirname(os.path.abspath(__file__))
NF, PF = "sky130_fd_pr/nfet_01v8.sym", "sky130_fd_pr/pfet_01v8.sym"
bus = lambda n, w=8: [f"{n}_{i}" for i in range(w)]

# --- adc_digital symbol (pin order = gl2spice .subckt: VDPWR VGND clk rst_n ui_in_0..7 uio_in_0..7 q | outputs)
dins = ["clk", "rst_n"] + bus("ui_in") + bus("uio_in") + ["q"]
douts = bus("uo_out") + bus("uio_out") + bus("uio_oe") + ["smp", "smpt", "cmp_clk"] + bus("b") + ["ref_sel", "vref_oe", "bg_pd"] + bus("insel", 2)
sym = Schematic(); sym.port("VDPWR", "inout"); sym.port("VGND", "inout")
for p_ in dins: sym.port(p_, "in")
for p_ in douts: sym.port(p_, "out")
sym.write_symbol(os.path.join(HERE, "adc_digital.sym"))

s = Schematic(cols=4, dx=900, dy=800)
for p_, d in ([("VDPWR", "inout"), ("VGND", "inout")] + [(x, "in") for x in bus("ui_in")] + [(x, "out") for x in bus("uo_out")]
              + [(x, "in") for x in bus("uio_in")] + [(x, "out") for x in bus("uio_out")] + [(x, "out") for x in bus("uio_oe")]
              + [(x, "inout") for x in bus("ua")] + [("ena", "in"), ("clk", "in"), ("rst_n", "in")]):
    s.port(p_, d)
s.text("tt_um_chiranjitpatel_sar_adc — bandgap-referenced 8-bit SAR ADC + temperature sensor (generated by gen_top.py)")
c = {"VDPWR": "VDPWR", "VGND": "VGND", "clk": "clk", "rst_n": "rst_n", "q": "q", "smp": "smp", "smpt": "smpt",
     "cmp_clk": "cmp_clk", "ref_sel": "ref_sel", "vref_oe": "vref_oe", "bg_pd": "bg_pd"}
c.update({x: x for x in bus("ui_in") + bus("uio_in") + bus("uo_out") + bus("uio_out") + bus("uio_oe") + bus("b") + bus("insel", 2)})
s.dev("adc_digital.sym", "xdig", c)
s.dev("bias_gen.sym", "xbias", {"VDPWR": "VDPWR", "VGND": "VGND", "pd": "VGND", "nbias": "nbias", "pbias": "pbias"})
s.dev("bandgap_core.sym", "xbg", {"VDPWR": "VDPWR", "VGND": "VGND", "pbias": "pbias", "pd": "bg_pd", "vbg": "vbg", "vgp": "vgp"})
s.dev("ptat_out.sym", "xptat", {"VDPWR": "VDPWR", "VGND": "VGND", "vgp": "vgp", "vptat": "vptat"})
s.dev("vref_filt.sym", "xfilt", {"VGND": "VGND", "vbg": "vbg", "vbg_f": "vbg_f"})
s.dev("vref_buf.sym", "xbuf", {"VDPWR": "VDPWR", "VGND": "VGND", "nbias": "nbias", "en": "en_buf", "in": "vbg_f", "vref": "vref"})
s.dev("vref_sel.sym", "xsel", {"VDPWR": "VDPWR", "VGND": "VGND", "ref_sel": "ref_sel", "vref_oe": "vref_oe", "bg_pd": "bg_pd",
                               "en_buf": "en_buf", "vref": "vref", "pad": "ua_1"})
s.dev("inmux.sym", "xmux", {"VDPWR": "VDPWR", "VGND": "VGND", "insel0": "insel_0", "insel1": "insel_1",
                            "vin": "ua_0", "vptat": "vptat", "vbg": "vbg", "vadc": "vadc"})
s.dev("vcm_gen.sym", "xvcm", {"VDPWR": "VDPWR", "VGND": "VGND", "pbias": "pbias", "smp": "smpt", "vtop": "vtop", "vcm": "vcm"})
dac = {"VDPWR": "VDPWR", "VGND": "VGND", "vref": "vref", "vadc": "vadc", "smp": "smp", "smpb": "smpb", "vtop": "vtop"}
dac.update({f"b{i}": f"b_{i}" for i in range(8)})
s.dev("cap_dac.sym", "xdac", dac)
s.dev("comparator.sym", "xcmp", {"VDPWR": "VDPWR", "VGND": "VGND", "pbias": "pbias", "clk": "cmp_clk", "inp": "vtop", "inn": "vcm", "q": "q", "qb": "qb"})
s.dev(PF, "MIP", {"D": "smpb", "G": "smp", "S": "VDPWR", "B": "VDPWR"}, model="pfet_01v8", spiceprefix="X", W=1.68, L=0.15, nf=1, mult=1)
s.dev(NF, "MIN", {"D": "smpb", "G": "smp", "S": "VGND", "B": "VGND"}, model="nfet_01v8", spiceprefix="X", W=0.84, L=0.15, nf=1, mult=1)
# ua[2..7] are not connected to pads (2 analog pins bought); they stay unconnected ports here and are
# tied to VGND with metal in the layout (TT: no floating pins). LVS: declare that tie when layout exists.
# ena is unused.
s.write(os.path.join(HERE, "tt_um_chiranjitpatel_sar_adc.sch"), sym=True)
print("wrote xschem/adc_digital.sym, tt_um_chiranjitpatel_sar_adc.sch/.sym")
