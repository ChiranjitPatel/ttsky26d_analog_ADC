#!/usr/bin/env python3
"""Stage 5 — vref_sel: reference selection logic and the ua[1] transmission gate.

Generates xschem/vref_sel.sch + .sym.   python3 xschem/gen_vref_sel.py
  en_buf = NOT(ref_sel OR bg_pd)        buffer on only when the internal reference is used
  en_pad = ref_sel OR vref_oe           TG vref <-> pad on for an external reference or a DMM readout
TG: nfet_01v8 + pfet_01v8_lvt (vref sits at 1.0-1.8 V, where a regular pfet has little overdrive).
Static CMOS gates, minimum-ish sizes.
Ports: VDPWR VGND ref_sel vref_oe bg_pd en_buf vref pad
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))
from xsch import Schematic
NF, PF, PFL = "sky130_fd_pr/nfet_01v8.sym", "sky130_fd_pr/pfet_01v8.sym", "sky130_fd_pr/pfet_01v8_lvt.sym"
TGN_W, TGP_W = 10, 20
s = Schematic()
for p_, d in (("VDPWR", "inout"), ("VGND", "inout"), ("ref_sel", "in"), ("vref_oe", "in"), ("bg_pd", "in"),
              ("en_buf", "out"), ("vref", "inout"), ("pad", "inout")):
    s.port(p_, d)
s.text("vref_sel — reference select logic + ua[1] transmission gate (generated by gen_vref_sel.py)")
def n(name, d, g, src, W=0.42, L=0.15, **k): s.dev(NF, name, {"D": d, "G": g, "S": src, "B": "VGND"}, model="nfet_01v8", spiceprefix="X", W=W, L=L, nf=1, mult=1, **k)
def p(name, d, g, src, W=0.84, L=0.15, sym=PF, model="pfet_01v8", **k): s.dev(sym, name, {"D": d, "G": g, "S": src, "B": "VDPWR"}, model=model, spiceprefix="X", W=W, L=L, nf=1, mult=1, **k)
# NOR2(ref_sel, bg_pd) = en_buf
p("MP1A", "nb1", "ref_sel", "VDPWR", W=1.68); p("MP1B", "en_buf", "bg_pd", "nb1", W=1.68)
n("MN1A", "en_buf", "ref_sel", "VGND"); n("MN1B", "en_buf", "bg_pd", "VGND")
# NOR2(ref_sel, vref_oe) = en_pad_b ; INV -> en_pad
p("MP2A", "nb2", "ref_sel", "VDPWR", W=1.68); p("MP2B", "en_pad_b", "vref_oe", "nb2", W=1.68)
n("MN2A", "en_pad_b", "ref_sel", "VGND"); n("MN2B", "en_pad_b", "vref_oe", "VGND")
p("MP3", "en_pad", "en_pad_b", "VDPWR"); n("MN3", "en_pad", "en_pad_b", "VGND")
# transmission gate vref <-> pad
n("MTGN", "pad", "en_pad", "vref", W=TGN_W, L=0.15)
p("MTGP", "pad", "en_pad_b", "vref", W=TGP_W, L=0.35, sym=PFL, model="pfet_01v8_lvt")
s.write(os.path.join(os.path.dirname(os.path.abspath(__file__)), "vref_sel.sch"), sym=True)
print("wrote xschem/vref_sel.sch, vref_sel.sym")
